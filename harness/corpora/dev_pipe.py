"""`F-DEV-PIPE` — the small recorded corpus every M-PIPE case drives against.

Gap-fix test plan §4.4 fixes the shape: *"3 submissions × 1 question × 3 criteria (2 judged,
1 MCQ-deterministic), with `F-RECORDED` responses for every extraction, panel call and
narrative. One criterion's recorded panel bands are `(2,4,4)`, so `should_escalate` fires; the
escalation calls are recorded too."*

The ids are the plan's own, not invented here. TC-PIPE-08 names cell `(R,S1,C2)` and TC-PIPE-05
names *"submission `S2`, criterion `C1`"*, so the submissions are `S1`..`S3` and the criteria
`C1`..`C3`. A corpus that renamed them would make those cases unwritable as specified.

Three disclosed divergences from §4.4's one-line description
------------------------------------------------------------
Each is forced by the shipped code or by the plan's own numbers, and each is reported on #435
rather than smoothed over.

**Two questions, not one, because a question is single-kind in the ingest ladder.** §4.4 says
*"1 question × 3 criteria (2 judged, 1 MCQ-deterministic)"*. V2 structural completeness builds
its declared inventory as ``{row["question_id"]: row["kind"] for row in catalog.criteria(v)}``
(`ingest.py:4303`) — a dict keyed by question. A question carrying criteria of BOTH kinds
therefore collapses to whichever criterion the catalog returns last, and the open criteria's
prose is then rejected as *"prose where the package declares mcq"*. So the MCQ criterion sits
on its own `Q2`. The reference package never exposes this because each of its questions is
single-kind; F-DEV-PIPE would have been the first corpus to mix them. The collapse itself is a
defect — it drops criteria silently rather than refusing — and is filed separately.

**A six-band open scale, because `(2,4,4)` has to be expressible.** The reference package's
open criteria carry four bands, ordinals 0..3 (`reference_package.OPEN_BANDS`). On that scale
the ordinal `4` the plan names does not exist, and neither do the points — a four-band
criterion tops out at 3. `FR-SETUP-04` / `CT-PKG-04` require an **even** `band_count` in 2..6,
so six is the smallest legal scale on which `(2,4,4)` is a literal panel of ordinals. It also
puts the panel's median at ordinal 4, which is *interior* (neither `0` nor `5`) — and the
interior-band limb is the first signal `agg.should_escalate` reads (`FR-AGG-08`, §7.1). So the
plan's literal numbers and the behaviour they are supposed to produce hold together on a
six-band scale and on no smaller one.

**Its own generator, because the reference generator is bound to the reference package.**
§4.4 says F-DEV-PIPE is *"drawn from F-DEV's generator"*. `synth.generate` iterates
`reference_package.CRITERIA` and renders through a four-entry table indexed by band ordinal
(`synth._OPEN_RENDERING`), so it cannot emit a three-criterion, six-band package at all. What
is preserved is the thing the phrase is *for*: the same construction — a per-criterion claim,
reason and condition, raised through the scale by a table indexed on ordinal — so a `secure`
page really does contain more of the construct than an `emerging` one, and the corpus is not
a set of pages differing by a random word.

Determinism
-----------
Bands are **assigned**, not drawn. The corpus is three submissions and every M-PIPE case reads
specific cells by name; a seeded draw would make `(2,4,4)` an accident of the seed and would
let a generator change silently move the cell TC-PIPE-08 asserts on. `DEV_PIPE_SEED` is still
declared and still written into the manifest, because §8.1's reproducibility check reads it and
because a corpus that claims no seed cannot be regenerated by anyone who did not write it.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Mapping

from harness.corpora.reference_package import Band, Criterion, Question, _bands

PACKAGE_ID = "PKG-DEV-PIPE"
PACKAGE_VERSION = "1"

#: Declared for the manifest and for regeneration. Nothing here draws from it — see the module
#: docstring on why the bands are assigned.
DEV_PIPE_SEED = 20260104

DEV_PIPE_COUNT = 3
PAGES_PER_SUBMISSION = 1

#: The six-band open scale, ordered by ordinal ascending (`CT-PKG-04`). Six because `(2,4,4)`
#: must be expressible as ordinals and 4 does not exist on the reference package's four-band
#: scale; even and within 2..6, as `FR-SETUP-04` requires.
OPEN_BANDS: tuple[tuple[str, int, float, str], ...] = (
    ("absent", 0, 0.0, "No work addressing this criterion appears."),
    ("minimal", 1, 1.0, "The work gestures at the idea without stating it."),
    ("emerging", 2, 2.0, "The work names the idea but does not carry it through."),
    ("developing", 3, 3.0, "The work carries the idea through with a stated gap."),
    ("secure", 4, 4.0, "The work carries the idea through and states its grounds."),
    ("comprehensive", 5, 5.0, "The work carries the idea through and states its limits."),
)

#: The two-band MCQ scale, named `incorrect` / `correct` rather than `FR-SETUP-04`'s
#: `met` / `not_met` default.
#:
#: `M-DET` does not read these names from anywhere — `det._score_one` produces the outcome
#: band itself and then asks the catalog to price it (`det.py:1681` →
#: `pkg.points_for_band`), which raises `PackageError: criterion 'C3' declares no band
#: 'correct'` against a met/not-met catalog. So the package declares the names the
#: deterministic evaluator actually scores with; the same disclosure `tests/support/e2e_world`
#: carries for the reference world. Declaring the setup default here would make the corpus
#: undrivable, and the corpus's whole purpose is being driven.
MCQ_BANDS: tuple[tuple[str, int, float, str], ...] = (
    ("incorrect", 0, 0.0, "The selected option is not the keyed option."),
    ("correct", 1, 1.0, "The selected option is the keyed option."),
)

MCQ_OPTIONS: tuple[str, ...] = ("A", "B", "C", "D")

#: The judged question and the MCQ question — two, for the reason the module docstring gives.
#: The subject is the reference package's ramp question, so a reader moving between the two
#: corpora is reading about the same physics.
QUESTIONS: tuple[Question, ...] = (
    Question(
        "Q1",
        "A crate rests on a ramp inclined at 25 degrees. Draw and label the forces acting on "
        "the crate, then explain why it does not slide.",
        "free_body_diagram",
    ),
    Question(
        "Q2",
        "Select the best answer for the item below.",
        None,
    ),
)

_OPEN_SPECS: tuple[tuple[str, str, str], ...] = (
    ("C1", "Q1", "Identifies every force acting on the crate and no force that is absent."),
    ("C2", "Q1", "Explains equilibrium in terms of the component along the ramp."),
)

_MCQ_SPECS: tuple[tuple[str, str, str, str], ...] = (
    ("C3", "Q2", "Item 2a: the direction of the net force on the crate.", "B"),
)

CRITERIA: tuple[Criterion, ...] = tuple(
    Criterion(cid, qid, "open", text, _bands(OPEN_BANDS)) for cid, qid, text in _OPEN_SPECS
) + tuple(
    Criterion(cid, qid, "mcq", text, _bands(MCQ_BANDS), answer_key=(key,))
    for cid, qid, text, key in _MCQ_SPECS
)

CRITERION_IDS: tuple[str, ...] = tuple(c.criterion_id for c in CRITERIA)
OPEN_CRITERION_IDS: tuple[str, ...] = tuple(c.criterion_id for c in CRITERIA if c.kind == "open")
MCQ_CRITERION_IDS: tuple[str, ...] = tuple(c.criterion_id for c in CRITERIA if c.kind == "mcq")

MAX_POINTS: float = sum(c.bands[-1].points for c in CRITERIA)

BY_ID: Mapping[str, Criterion] = {c.criterion_id: c for c in CRITERIA}

#: How a band renders as student work, indexed by ordinal — the same construction
#: `synth._OPEN_RENDERING` uses, widened to six entries for the six-band scale.
_OPEN_RENDERING: tuple[str, ...] = (
    "I did not get to this part.",
    "Something about {topic}, but I ran out of time.",
    "{claim}.",
    "{claim}, because {reason}.",
    "{claim}, because {reason}, and this holds as long as {condition}.",
    "{claim}, because {reason}, and this holds as long as {condition}; it fails once {limit}.",
)

#: Per-criterion phrasing: the claim the criterion is about, and the reason, condition and
#: limit that raise it through the scale. Written out rather than generated, for the reason
#: `harness.corpora.synth` gives — a corpus whose bands differ only in a random word is a
#: corpus no agreement figure means anything against.
_PHRASING: Mapping[str, tuple[str, str, str, str]] = {
    "C1": (
        "the forces on the crate",
        "The crate has weight down, the normal force out of the ramp, and friction up the slope",
        "nothing else is touching it",
        "the ramp surface stays in contact",
        "the crate leaves the surface",
    ),
    "C2": (
        "why the crate stays put",
        "The crate stays put because friction balances the weight component along the ramp",
        "the two along-ramp forces are equal and opposite",
        "the required friction stays under the limiting value",
        "the ramp is tilted past the friction angle",
    ),
}


def render_band(criterion_id: str, ordinal: int) -> str:
    """One open criterion rendered as student prose at one band ordinal."""
    topic, claim, reason, condition, limit = _PHRASING[criterion_id]
    return _OPEN_RENDERING[ordinal].format(
        topic=topic, claim=claim, reason=reason, condition=condition, limit=limit
    )


def points_for(criterion_id: str, band: str) -> float:
    """The band→points mapping for this package, so a fixture's declared reference points and
    its declared reference bands cannot disagree."""
    for b in BY_ID[criterion_id].bands:
        if b.band == band:
            return b.points
    raise KeyError(
        f"{band!r} is not a band of {criterion_id} (CT-JUDGE-04: never mapped or rounded)"
    )


def band_at(criterion_id: str, ordinal: int) -> str:
    """The band NAME at an ordinal — the form the store and the recorded verdicts carry."""
    return BY_ID[criterion_id].bands[ordinal].band


# --- the assigned cohort --------------------------------------------------------------------

#: The panel a judged criterion records, as band ORDINALS in panel order.
#:
#: Only `C2` appears, carrying §4.4's `(2,4,4)` — it is *"one criterion's recorded panel
#: bands"*, so the disagreement is a property of the criterion rather than of one cell. A
#: criterion absent from this table has a UNANIMOUS panel at the submission's own reference
#: band, which is `SynthWorld`'s behaviour and the reason `C1` reads differently on each of the
#: three submissions instead of being a constant that ignores the student's work.
PANEL_ORDINALS: Mapping[str, tuple[int, ...]] = {
    "C2": (2, 4, 4),
}

#: The two extension arms the ladder adds when `should_escalate` fires (`units_consumed=5` in
#: TC-PIPE-08's second aggregation: the panel of three plus these two).
#:
#: `C2` names them because its panel disagrees and the arms have to settle it. `C1` does not,
#: and escalates anyway — on EVERY submission, measured, including `absent` at ordinal 0 where
#: the panel is unanimous and the band is an edge:
#:
#:     C1 absent        -> ('distributional anomaly vs package baseline (z=-4.00)',)
#:     C1 developing    -> ('interior band position', 'distributional anomaly ... (z=2.00)')
#:     C1 comprehensive -> ('distributional anomaly vs package baseline (z=6.00)',)
#:     C2 secure        -> ('interior band position', 'distributional anomaly ... (z=4.00)')
#:
#: The anomaly limb alone clears the threshold, because the aggregation baseline every walk
#: passes (`tests/support/agg_vocabulary.expected_distribution`, `mean=2.0, std=0.5`) is
#: calibrated for the reference package's FOUR-band scale; on six bands the same ordinals sit
#: several sigma out. So this corpus escalates every judged cell, and `(2,4,4)` is not what
#: causes it — `should_escalate` has no panel-spread limb at all (`FR-AGG-08`, §7.1). §4.4's
#: `(2,4,4)` still holds literally: the panel is recorded as specified and the criterion does
#: escalate. What the corpus cannot currently demonstrate is the NON-escalating path, which
#: would need a baseline scaled to this package. Recorded here rather than left for a reader
#: to rediscover, and noted on #435.
#:
#: Every arm not named here answers at the submission's own reference band, the same as its
#: panel — which is why the escalated cells still settle on the corpus's reference labels.
ESCALATION_ORDINALS: Mapping[str, tuple[int, ...]] = {
    "C2": (4, 4),
}


#: `F-DEV-PIPE-TWO-RUN` — the two recorded response sets every two-run isolation case drives.
#:
#: §4.4: *"F-DEV-PIPE plus a second recorded response set whose bands differ on every judged
#: criterion (`(1,1,1)` → `(3,3,3)`)"*. Same submissions, same package, same extraction; only
#: the verdicts move. Each run's panel is UNANIMOUS at one ordinal — that is what `(1,1,1)`
#: and `(3,3,3)` say — so every judged cell of run A sits two bands below its twin in run B,
#: and a figure that leaked from B into A is visible as a band, not as a rounding difference.
#:
#: **They cannot share a directory, and this is the reason.** A judge request is keyed on the
#: assembled prompt — directive, criterion, bands, then the submission and its extracted
#: evidence (`judge.prompt_fields`, `FR-JUDGE-07`). No run identifier appears in it, and the
#: two runs have the same submissions and the same extraction. So run A's `minimal` verdict
#: and run B's `developing` verdict are answers to a BYTE-IDENTICAL request, and one
#: `request_key` cannot hold both. Each set therefore gets its own recordings directory and a
#: consumer points the provider at one per run.
#:
#: TC-GRADE-25 drives A, lands B, and re-reads A; ADV-13 reads run B as a re-run after a key
#: correction. ADV-13's prose says run B is *"all bands at the top"* where §4.4 says `(3,3,3)`;
#: the literal numbers are what ships, since `(3,3,3)` is what makes the pair differ on every
#: judged criterion without either run sitting on a scale edge.
TWO_RUN_ORDINALS: Mapping[str, int] = {
    "run-a": 1,
    "run-b": 3,
}


@dataclass(frozen=True)
class PipeSubmission:
    """One F-DEV-PIPE submission: the student work, and the reference labels for it."""

    submission_id: str
    student_ref: str
    bands: Mapping[str, str]
    mcq_choices: Mapping[str, str]
    pages: tuple[str, ...]

    @property
    def reference_points(self) -> float:
        return sum(points_for(cid, band) for cid, band in self.bands.items())

    def as_document(self) -> str:
        """The committed form: a header, then the pages with their markers — byte-identical in
        shape to `synth.SyntheticSubmission.as_document`, so one manifest shape covers both."""
        header = [
            f"# Submission {self.submission_id}",
            "",
            f"student_ref: {self.student_ref}",
            "consent_class: synthetic",
            "",
        ]
        body: list[str] = []
        for index, page in enumerate(self.pages, start=1):
            body.append(f"<!-- page: {index} of {len(self.pages)} -->")
            body.append(page)
            body.append("")
        return "\n".join(header + body).rstrip("\n")


#: Each submission's open-criterion ordinals and whether its MCQ answer is the keyed one.
#:
#: `C2` sits at ordinal 4 throughout — the median of its `(2,4,4)` panel, so the rendered work
#: and the verdict the panel settles on describe the same thing. `C1` and the MCQ vary across
#: the three, so the corpus is not three copies of one submission: an absent opening, a
#: developing middle and a comprehensive one, with the MCQ right, wrong and right.
_ASSIGNED: tuple[tuple[str, str, Mapping[str, int], bool], ...] = (
    ("S1", "P-0001", {"C1": 0, "C2": 4}, True),
    ("S2", "P-0002", {"C1": 3, "C2": 4}, False),
    ("S3", "P-0003", {"C1": 5, "C2": 4}, True),
)


def _page_text(submission_id: str, ordinals: Mapping[str, int],
               mcq_choices: Mapping[str, str]) -> str:
    lines = [
        f"Page 1 of {PAGES_PER_SUBMISSION} - {submission_id}",
        "",
        f"## {QUESTIONS[0].question_id}",
        "",
    ]
    for cid in OPEN_CRITERION_IDS:
        lines.append(render_band(cid, ordinals[cid]))
    # The MCQ question gets its own `##` heading: the marker protocol keys a region to the
    # heading it sits under, and without this the item line is swept into Q1's prose region —
    # which V2 then rejects, because Q1 is declared open and the region carries an mcq answer.
    lines += ["", f"## {QUESTIONS[1].question_id}", ""]
    for cid in MCQ_CRITERION_IDS:
        lines.append(f"{cid}: {mcq_choices[cid]}")
    return "\n".join(lines)


def _generate(submission_id: str, student_ref: str, ordinals: Mapping[str, int],
              mcq_correct: bool) -> PipeSubmission:
    bands = {cid: band_at(cid, ordinal) for cid, ordinal in ordinals.items()}
    mcq_choices: dict[str, str] = {}
    for cid in MCQ_CRITERION_IDS:
        key = BY_ID[cid].answer_key[0]
        # The wrong answer is the first non-keyed option rather than a drawn one: assigned
        # bands and a drawn distractor would make only half of this corpus reproducible by
        # inspection.
        choice = key if mcq_correct else next(o for o in MCQ_OPTIONS if o != key)
        mcq_choices[cid] = choice
        bands[cid] = "correct" if mcq_correct else "incorrect"
    pages = (_page_text(submission_id, ordinals, mcq_choices),)
    return PipeSubmission(
        submission_id=submission_id,
        student_ref=student_ref,
        bands=bands,
        mcq_choices=mcq_choices,
        pages=pages,
    )


def dev_pipe_set() -> tuple[PipeSubmission, ...]:
    """`F-DEV-PIPE` — the three submissions every M-PIPE case drives."""
    return tuple(
        _generate(sid, ref, ordinals, mcq_correct)
        for sid, ref, ordinals, mcq_correct in _ASSIGNED
    )


def as_json() -> dict[str, object]:
    """The package as committed data, for the corpus manifest and the capture pass."""
    return {
        "package_id": PACKAGE_ID,
        "package_version": PACKAGE_VERSION,
        "max_points": MAX_POINTS,
        "questions": [
            {"question_id": q.question_id, "prompt": q.prompt, "element_kind": q.element_kind}
            for q in QUESTIONS
        ],
        "criteria": [
            {
                "criterion_id": c.criterion_id,
                "question_id": c.question_id,
                "kind": c.kind,
                "text": c.text,
                "answer_key": list(c.answer_key),
                "bands": [
                    {
                        "band": b.band,
                        "ordinal": b.ordinal,
                        "points": b.points,
                        "descriptor": b.descriptor,
                    }
                    for b in c.bands
                ],
            }
            for c in CRITERIA
        ],
        "panel_ordinals": {cid: list(v) for cid, v in PANEL_ORDINALS.items()},
        "escalation_ordinals": {cid: list(v) for cid, v in ESCALATION_ORDINALS.items()},
    }
