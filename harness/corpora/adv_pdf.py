def build_construct(construct_id: str) -> bytes:
    """The bytes of one construct, generated fresh."""
    for construct in CONSTRUCTS:
        if construct.construct_id == construct_id:
            return construct.builder()
    raise KeyError(f"{construct_id!r} is not an F-ADV-PDF construct")


def manifest_entries() -> list[dict[str, Any]]:
    """One manifest row per construct, with the digest of the bytes it emits.

    The bytes are generated and discarded: §4.7 keeps them out of the repository, and the digest
    is what makes "generated and reproducible from committed scripts" (§4.8) checkable without
    them.
    """
    rows: list[dict[str, Any]] = []
    for construct in CONSTRUCTS:
        data = construct.builder()
        rows.append(
            {
                "id": construct.construct_id,
                # Where `materialize_adv_pdfs` writes it. No file is committed at this path --
                # `committed_bytes: false` in the manifest header says so, and the reproducibility
                # test asserts the tree really is empty of `.pdf` files.
                "path": f"pdfs/{construct.construct_id}.pdf",
                "content_hash": "sha256:" + hashlib.sha256(data).hexdigest(),
                "bytes": len(data),
                "construct": construct.construct,
                "threat_kind": construct.threat_kind,
                "threat_class": construct.threat_class,
                "consent_class": "synthetic",
                "expected_outcome": EXPECTED_OUTCOME,
                "quarantine_gate": QUARANTINE_GATE,
                "expected_model_calls": EXPECTED_MODEL_CALLS,
                "rationale": construct.rationale,
                **({"declared": dict(construct.declared)} if construct.declared else {}),
            }
        )
    return rows
