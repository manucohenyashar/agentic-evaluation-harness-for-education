#!/bin/bash
# Checks that the requirement/test-case IDs in the planning documents survived the
# transcription into GitHub issues, and that every story/test issue carries the fields the
# implementation skills depend on.
#
# The RTM in the test plan proves FR -> TC. This proves TC/FR -> issue. Without it the
# traceability chain silently ends at the GitHub boundary, which is exactly where work
# starts getting dropped.
#
# Usage:   ./scripts/trace-issues.sh <docs-path> [docs-path ...]
#          (files or directories; directories are searched recursively for .md files)
# Requires: gh (authenticated), jq, GNU grep
#
# Exit 0 = clean, 1 = gaps found, 2 = could not run.

set -uo pipefail

if [ "$#" -lt 1 ]; then
  echo "usage: $0 <docs-path> [docs-path ...]" >&2
  exit 2
fi

for tool in gh jq; do
  command -v "$tool" >/dev/null 2>&1 || { echo "error: '$tool' is required but not installed" >&2; exit 2; }
done

REQ_RE='\b(FR|NFR)(-[A-Z0-9]+)*-[0-9]+\b'
TC_RE='\b(TC|UAT|PERF|SEC|ADV|FUZZ|RES|OBS|CS)(-[A-Z0-9]+)*-[0-9]+\b'
ID_RE="($REQ_RE|$TC_RE)"

# --- IDs defined in the planning documents -----------------------------------------
DOC_FILES=$(find "$@" -type f -name '*.md' 2>/dev/null | sort)
if [ -z "$DOC_FILES" ]; then
  echo "error: no .md documents found under: $*" >&2
  exit 2
fi

DOC_IDS=$(echo "$DOC_FILES" | xargs grep -ohE "$ID_RE" 2>/dev/null | sort -u)
if [ -z "$DOC_IDS" ]; then
  echo "error: no FR-*/NFR-*/TC-* IDs found in the documents." >&2
  echo "       Either the documents use a different ID scheme, or the design and test" >&2
  echo "       plan were not generated by /detailed-design-generator and /create-test-plan." >&2
  exit 2
fi

# --- What the issues claim to cover --------------------------------------------------
ISSUES=$(gh issue list --state all --limit 500 --json number,title,body,labels 2>/dev/null) || {
  echo "error: 'gh issue list' failed. Authenticate with 'gh auth login' and confirm this" >&2
  echo "       directory has a GitHub remote." >&2
  exit 2
}

WORK_ISSUES=$(echo "$ISSUES" | jq -c '
  [ .[] | select(.labels | map(.name) | any(. == "type:story" or . == "type:test")) ]')

COUNT=$(echo "$WORK_ISSUES" | jq 'length')
if [ "$COUNT" -eq 0 ]; then
  echo "error: no type:story / type:test issues found. Run /plan-to-issues first." >&2
  exit 2
fi

# "Traces to:" lines only -- an ID mentioned in passing in a technical note is not a claim
# of coverage, and counting it as one would make this check pass on issues that trace to
# nothing.
TRACE_LINES=$(echo "$WORK_ISSUES" | jq -r '.[].body // ""' | grep -iE '^\s*\*{0,2}Traces to:' || true)
ISSUE_IDS=$(echo "$TRACE_LINES" | grep -ohE "$ID_RE" 2>/dev/null | sort -u)

# --- Comparisons ----------------------------------------------------------------------
UNCOVERED=$(comm -23 <(echo "$DOC_IDS") <(echo "${ISSUE_IDS:-}"))
UNKNOWN=$(comm -13 <(echo "$DOC_IDS") <(echo "${ISSUE_IDS:-}"))

MISSING_TRACE=$(echo "$WORK_ISSUES" | jq -r '
  .[] | select((.body // "") | test("(?i)^\\s*\\*{0,2}Traces to:"; "m") | not)
      | "#\(.number) \(.title)"')

MISSING_GOAL=$(echo "$WORK_ISSUES" | jq -r '
  .[] | select((.body // "") | test("(?i)^\\s*\\*{0,2}Goal:"; "m") | not)
      | "#\(.number) \(.title)"')

# A dependency line whose numbers cannot be parsed is worse than no line: readiness logic
# would otherwise read it as "no dependencies" and start blocked work.
MALFORMED_DEPS=$(echo "$WORK_ISSUES" | jq -r '
  .[] | select((.body // "") | test("(?i)depends on:"))
      | select(((.body // "") | [scan("(?i)depends on:[^\\n]*")] | join(" ") | test("#[0-9]+")) | not)
      | "#\(.number) \(.title)"')

DOC_TOTAL=$(echo "$DOC_IDS" | grep -c . || true)
TRACED=$(comm -12 <(echo "$DOC_IDS") <(echo "${ISSUE_IDS:-}") | grep -c . || true)

echo "documents : $(echo "$DOC_FILES" | grep -c .)   work issues: $COUNT"
echo "IDs in docs: $DOC_TOTAL   traced to an issue: $TRACED"
echo

OK=0

report() { # $1 = heading, $2 = body, $3 = hint
  if [ -n "$2" ]; then
    OK=1
    echo "FAIL  $1"
    echo "$2" | sed 's/^/        /'
    [ -n "$3" ] && echo "      $3"
    echo
  fi
}

report "$(echo "$UNCOVERED" | grep -c .) ID(s) in the documents that no issue traces to:" \
       "$UNCOVERED" \
       "(each is planned work that will never be built -- add it to an issue's 'Traces to:' line, or create the missing issue)"

report "$(echo "$UNKNOWN" | grep -c .) ID(s) referenced by issues but absent from the documents:" \
       "$UNKNOWN" \
       "(typo, or work invented at the issue stage -- reconcile with the design or test plan)"

report "$(echo "$MISSING_TRACE" | grep -c .) issue(s) with no 'Traces to:' line:" \
       "$MISSING_TRACE" \
       "(untraceable work: nothing can confirm it implements anything that was designed)"

report "$(echo "$MISSING_GOAL" | grep -c .) issue(s) with no 'Goal:' line:" \
       "$MISSING_GOAL" \
       "(/fix-issue and /write-tests plan against the Goal, and the reviewer subagent checks the diff against it)"

report "$(echo "$MALFORMED_DEPS" | grep -c .) issue(s) with an unparseable 'Depends on:' line:" \
       "$MALFORMED_DEPS" \
       "(use literal issue numbers: 'Depends on: #12, #34', or omit the line entirely)"

if [ "$OK" -eq 0 ]; then
  echo "PASS  every documented ID traces to an issue; every work issue has a Goal, a"
  echo "      Traces to line, and a parseable dependency line."
  exit 0
fi

echo "Traceability check failed. The chain FR -> TC -> issue is broken at the points above."
exit 1
