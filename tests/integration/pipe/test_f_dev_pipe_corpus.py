"""Issue #435 — `F-DEV-PIPE` is a committed, replayable corpus.

| Case | Input | Expected |
|---|---|---|
| manifest | `fixtures/F-DEV-PIPE/manifest.json` | generator, seed and `set_content_hash` present; 3 submissions |
| shape | the declared package | 1 judged question, 2 open criteria, 1 mcq criterion |
| recordings | `fixtures/F-DEV-PIPE/recordings/` | a reply for every transcription, extraction, panel call, escalation call and narrative |
| panel | `dev_pipe.PANEL_ORDINALS["C2"]` | `(2,4,4)`, and the recorded verdicts carry those three bands |
| **replay** | a full run driven with `record_as_you_go=False` | every request replays; no recording is missed |

**The replay case is the one that matters.** The other four describe the corpus; this one is
the only assertion that cannot be satisfied by a pile of JSON that happens to sit in the right
directory. `StrictReplayProvider` raises on a miss instead of computing a reply, so a corpus
missing one recording fails here rather than quietly regenerating the gap — which is exactly
what `JourneyProvider` would do and why the replay world does not use it.

**Rung 3, because the corpus's claim is about the assembled pipeline.** The question F-DEV-PIPE
answers is whether a real run — ingest gateway, orchestrator, deterministic evaluator,
extraction workers, integrity gate, aggregation walk, synthesis worker and closer — can be
driven from committed bytes with no network. Nothing below that level can answer it: a unit
test over `RecordedFixtureProvider` proves the provider replays, not that the corpus is
complete for a run.

**The escalation half is asserted through `judge_count`, not through a spy.** `C2`'s panel is
`(2,4,4)`, so `should_escalate` fires on the interior median and the ladder adds two extension
arms; the cell then aggregates a second time over five verdicts. `judge_count == 5` on the
stored score is the observable end of that sequence and is what TC-PIPE-08 will assert the
ordering of. Asserting it here keeps this case about the corpus rather than about M-PIPE's
call order, which is #377's subject.
"""

from __future__ import annotations

import json

import pytest

from harness.corpora import dev_pipe
from tests.support.pipe_world import (
    drive_full_run,
    pinned_uuid4,
    recordings_dir,
    replay_world,
)

pytestmark = pytest.mark.integration

CORPUS_DIR = recordings_dir().parent


def _manifest() -> dict:
    return json.loads((CORPUS_DIR / "manifest.json").read_text(encoding="utf-8"))


def _recordings() -> list[dict]:
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(recordings_dir().glob("*.json"))
    ]


# --- the corpus is committed and shaped as the plan says ------------------------------------


def test_f_dev_pipe_manifest_carries_its_provenance() -> None:
    """A corpus that claims no generator and no seed cannot be regenerated by anyone who did
    not write it, and `set_content_hash` is what `--check` compares."""
    manifest = _manifest()
    assert manifest["generator"] == "harness.corpora.dev_pipe:dev_pipe_set"
    assert manifest["seed"] == dev_pipe.DEV_PIPE_SEED
    assert manifest["set_content_hash"].startswith("sha256:")
    assert manifest["package_id"] == dev_pipe.PACKAGE_ID
    assert len(manifest["submissions"]) == dev_pipe.DEV_PIPE_COUNT == 3


def test_f_dev_pipe_holds_two_judged_criteria_and_one_mcq() -> None:
    """§4.4's `3 submissions x 3 criteria (2 judged, 1 MCQ-deterministic)`.

    The question count is 2 rather than the plan's 1, for the reason `dev_pipe`'s module
    docstring gives: V2 classifies a question by a single `kind`, so a question carrying both
    an open and an mcq criterion is rejected. The criteria count — the half the M-PIPE cases
    actually address — is the plan's.
    """
    assert dev_pipe.OPEN_CRITERION_IDS == ("C1", "C2")
    assert dev_pipe.MCQ_CRITERION_IDS == ("C3",)
    assert [q.question_id for q in dev_pipe.QUESTIONS] == ["Q1", "Q2"]
    judged_question = {dev_pipe.BY_ID[cid].question_id for cid in dev_pipe.OPEN_CRITERION_IDS}
    assert judged_question == {"Q1"}, (
        "both judged criteria belong to one question - the plan's '1 question' for the judged "
        f"half: {judged_question}")


def test_f_dev_pipe_records_every_call_the_plan_names() -> None:
    """Extraction, panel, narrative — *and* the escalation calls, which §4.4 names separately
    because a corpus without them cannot drive the widened panel it asks for."""
    by_role: dict[str, int] = {}
    escalation_arms: set[str] = set()
    levels: set[str] = set()
    for document in _recordings():
        model_ref = document["request"]["model_ref"]
        by_role[model_ref["role"]] = by_role.get(model_ref["role"], 0) + 1
        if model_ref["build_id"].startswith("escalation-arm-"):
            escalation_arms.add(model_ref["build_id"])
        fields = dict(document["request"]["fields"])
        if "level" in fields:
            levels.add(fields["level"])

    assert by_role.get("transcriber"), "no transcription replies - ingest cannot run"
    assert by_role.get("extractor"), "no extraction replies"
    assert by_role.get("judge"), "no panel replies"
    assert by_role.get("synthesizer"), "no narrative replies"
    assert escalation_arms == {"escalation-arm-4", "escalation-arm-5"}, (
        f"the escalation calls §4.4 names are not recorded: {sorted(escalation_arms)}")
    assert levels == {"l1_question", "l2_test"}, (
        f"both narrative levels must be recorded, found {sorted(levels)}")


def test_f_dev_pipe_panel_on_c2_is_the_plans_two_four_four() -> None:
    """The declared panel, and the bands actually recorded for it.

    Asserted on the recordings rather than only on the table, because a table nothing reads
    would let the corpus and its declaration drift apart.
    """
    assert dev_pipe.PANEL_ORDINALS["C2"] == (2, 4, 4)
    expected = {dev_pipe.band_at("C2", ordinal) for ordinal in (2, 4, 4)}
    assert expected == {"emerging", "secure"}

    recorded = {
        json.loads(document["completion"]["text"])["band"]
        for document in _recordings()
        if document["request"]["model_ref"]["role"] == "judge"
        and not document["request"]["model_ref"]["build_id"].startswith("escalation-arm-")
        and "C2" in dict(document["request"]["fields"]).get("criterion", "")
    }
    assert recorded == expected, (
        f"C2's recorded panel carries {sorted(recorded)}, not the plan's (2,4,4) -> "
        f"{sorted(expected)}")


# --- the criterion that cannot be faked -----------------------------------------------------


def test_f_dev_pipe_drives_a_full_run_with_nothing_recorded_on_the_way(tmp_path) -> None:
    """#435's fifth acceptance criterion: a full run, no record-as-you-go, no missed recording.

    The provider raises on a miss, so this fails loudly if the corpus is incomplete. The band
    assertions are what make it more than a smoke test: replaying the wrong recording for a
    cell would still complete the run, and only the reference labels catch it.
    """
    with pinned_uuid4():
        world = replay_world(tmp_path / "data")
        try:
            drive_full_run(world)
            assert world.provider.misses == [], (
                f"requests with no recording: {world.provider.misses}")
            assert world.provider.replayed_calls > 0

            scores = {
                (row["submission_id"], row["criterion_id"]): row
                for row in world.handle.query(
                    "SELECT submission_id, criterion_id, band, judge_count FROM "
                    "criterion_score"
                )
            }
            assert len(scores) == 9, f"expected 3 submissions x 3 criteria, got {len(scores)}"

            for index, submission in enumerate(world.cohort, start=1):
                sid = world.sid_by_index[index]
                for cid, reference in submission.bands.items():
                    row = scores[(sid, cid)]
                    assert row["band"] == reference, (
                        f"{submission.submission_id}/{cid} scored {row['band']!r} against the "
                        f"corpus's reference band {reference!r} - the run replayed a recording "
                        "that does not belong to this cell")

            for index in world.sid_by_index:
                sid = world.sid_by_index[index]
                assert scores[(sid, "C2")]["judge_count"] == 5, (
                    "C2's (2,4,4) panel must escalate: three panel arms plus the ladder's two "
                    f"extension arms, got {scores[(sid, 'C2')]['judge_count']}")
                assert scores[(sid, "C3")]["judge_count"] == 0, (
                    "the mcq criterion is scored by M-DET, not by a panel")
        finally:
            world.store.close()
