"""Issue #435 — `F-DEV-PIPE` is a committed, replayable corpus.

| Case | Input | Expected |
|---|---|---|
| manifest | `fixtures/F-DEV-PIPE/manifest.json` | generator, seed and `set_content_hash` present; 3 submissions |
| shape | the declared package | 1 judged question, 2 open criteria, 1 mcq criterion |
| recordings | `fixtures/F-DEV-PIPE/recordings/` | a reply for every transcription, extraction, panel call, escalation call and narrative |
| panel | `dev_pipe.PANEL_ORDINALS["C2"]` | `(2,4,4)`, and the recorded verdicts carry those three bands |
| **replay** | a full run driven with `record_as_you_go=False` | every request replays; no recording is missed |

**The replay case is the one that matters.** The other four describe the corpus; this one is
the only assertion that cannot be satisfied by a pile of JSON that happens to sit in the right
directory. `StrictReplayProvider` raises on a miss instead of computing a reply, so a corpus
missing one recording fails here rather than quietly regenerating the gap — which is exactly
what `JourneyProvider` would do and why the replay world does not use it.

**Rung 3, because the corpus's claim is about the assembled pipeline.** The question F-DEV-PIPE
answers is whether a real run — ingest gateway, orchestrator, deterministic evaluator,
extraction workers, integrity gate, aggregation walk, synthesis worker and closer — can be
driven from committed bytes with no network. Nothing below that level can answer it: a unit
test over `RecordedFixtureProvider` proves the provider replays, not that the corpus is
complete for a run.

**The escalation half is asserted on the REASONS, not on `judge_count` alone.** An earlier
draft of this module claimed `judge_count == 5` showed that `(2,4,4)` caused the escalation.
It does not, and the claim was measured false: every judged cell of this corpus escalates,
`C1` at `absent` included — ordinal 0, an edge band, unanimous panel — because the
aggregation baseline the walk passes is calibrated for the reference package's four-band
scale and puts six-band ordinals several sigma out. `should_escalate` has no panel-spread limb
at all (`FR-AGG-08`, §7.1), so a `judge_count` assertion passes with a unanimous panel and
discriminates nothing.

What IS panel-dependent is the band the panel settles on, and that is what the reasons record:
`C2`'s aggregate lands `secure` — interior on a six-band scale — so `interior band position`
appears among its escalation reasons. That assertion fails if the panel moves to an edge, and
it is the honest form of §4.4's claim. `judge_count == 5` is still asserted, as the observable
end of the ladder having run; it is simply not evidence about *why*.
"""

from __future__ import annotations

import json

import pytest

from harness.corpora import dev_pipe
from tests.support.pipe_world import (
    drive_full_run,
    drive_second_run,
    recordings_dir,
    replay_world,
    two_run_dir,
    two_run_replay_world,
)

pytestmark = pytest.mark.integration

CORPUS_DIR = recordings_dir().parent


def _manifest() -> dict:
    return json.loads((CORPUS_DIR / "manifest.json").read_text(encoding="utf-8"))


def _recordings() -> list[dict]:
    return [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(recordings_dir().glob("*.json"))
    ]


# --- the corpus is committed and shaped as the plan says ------------------------------------


def test_f_dev_pipe_manifest_carries_its_provenance() -> None:
    """A corpus that claims no generator and no seed cannot be regenerated by anyone who did
    not write it, and `set_content_hash` is what `--check` compares."""
    manifest = _manifest()
    assert manifest["generator"] == "harness.corpora.dev_pipe:dev_pipe_set"
    assert manifest["seed"] == dev_pipe.DEV_PIPE_SEED
    assert manifest["set_content_hash"].startswith("sha256:")
    assert manifest["package_id"] == dev_pipe.PACKAGE_ID
    assert len(manifest["submissions"]) == dev_pipe.DEV_PIPE_COUNT == 3


def test_f_dev_pipe_holds_two_judged_criteria_and_one_mcq() -> None:
    """§4.4's `3 submissions x 3 criteria (2 judged, 1 MCQ-deterministic)`.

    The question count is 2 rather than the plan's 1, for the reason `dev_pipe`'s module
    docstring gives: V2 classifies a question by a single `kind`, so a question carrying both
    an open and an mcq criterion is rejected. The criteria count — the half the M-PIPE cases
    actually address — is the plan's.
    """
    assert dev_pipe.OPEN_CRITERION_IDS == ("C1", "C2")
    assert dev_pipe.MCQ_CRITERION_IDS == ("C3",)
    assert [q.question_id for q in dev_pipe.QUESTIONS] == ["Q1", "Q2"]
    judged_question = {dev_pipe.BY_ID[cid].question_id for cid in dev_pipe.OPEN_CRITERION_IDS}
    assert judged_question == {"Q1"}, (
        "both judged criteria belong to one question - the plan's '1 question' for the judged "
        f"half: {judged_question}")


def test_f_dev_pipe_records_every_call_the_plan_names() -> None:
    """Extraction, panel, narrative — *and* the escalation calls, which §4.4 names separately
    because a corpus without them cannot drive the widened panel it asks for."""
    by_role: dict[str, int] = {}
    escalation_arms: set[str] = set()
    levels: set[str] = set()
    for document in _recordings():
        model_ref = document["request"]["model_ref"]
        by_role[model_ref["role"]] = by_role.get(model_ref["role"], 0) + 1
        if model_ref["build_id"].startswith("escalation-arm-"):
            escalation_arms.add(model_ref["build_id"])
        fields = dict(document["request"]["fields"])
        if "level" in fields:
            levels.add(fields["level"])

    assert by_role.get("transcriber"), "no transcription replies - ingest cannot run"
    assert by_role.get("extractor"), "no extraction replies"
    assert by_role.get("judge"), "no panel replies"
    assert by_role.get("synthesizer"), "no narrative replies"
    assert escalation_arms == {"escalation-arm-4", "escalation-arm-5"}, (
        f"the escalation calls §4.4 names are not recorded: {sorted(escalation_arms)}")
    assert levels == {"l1_question", "l2_test"}, (
        f"both narrative levels must be recorded, found {sorted(levels)}")


def test_f_dev_pipe_panel_on_c2_is_the_plans_two_four_four() -> None:
    """The declared panel, and the bands actually recorded for it.

    Asserted on the recordings rather than only on the table, because a table nothing reads
    would let the corpus and its declaration drift apart.
    """
    assert dev_pipe.PANEL_ORDINALS["C2"] == (2, 4, 4)
    expected = {dev_pipe.band_at("C2", ordinal) for ordinal in (2, 4, 4)}
    assert expected == {"emerging", "secure"}

    recorded = {
        json.loads(document["completion"]["text"])["band"]
        for document in _recordings()
        if document["request"]["model_ref"]["role"] == "judge"
        and not document["request"]["model_ref"]["build_id"].startswith("escalation-arm-")
        and "C2" in dict(document["request"]["fields"]).get("criterion", "")
    }
    assert recorded == expected, (
        f"C2's recorded panel carries {sorted(recorded)}, not the plan's (2,4,4) -> "
        f"{sorted(expected)}")


# --- the criterion that cannot be faked -----------------------------------------------------


def test_f_dev_pipe_drives_a_full_run_with_nothing_recorded_on_the_way(tmp_path) -> None:
    """#435's fifth acceptance criterion: a full run, no record-as-you-go, no missed recording.

    The provider raises on a miss, so this fails loudly if the corpus is incomplete. The band
    assertions are what make it more than a smoke test: replaying the wrong recording for a
    cell would still complete the run, and only the reference labels catch it.

    No `uuid4` pinning here on purpose: `PipeWorld` pins its own construction, and a consumer
    that had to remember the trick would be a corpus that only replays for whoever built it.
    """
    world = replay_world(tmp_path / "data")
    try:
        drive_full_run(world)
        assert world.provider.misses == [], (
            f"requests with no recording: {world.provider.misses}")
        assert world.provider.replayed_calls > 0

        scores = {
            (row["submission_id"], row["criterion_id"]): row
            for row in world.handle.query(
                "SELECT submission_id, criterion_id, band, judge_count FROM "
                "criterion_score"
            )
        }
        assert len(scores) == 9, f"expected 3 submissions x 3 criteria, got {len(scores)}"

        for index, submission in enumerate(world.cohort, start=1):
            sid = world.sid_by_index[index]
            for cid, reference in submission.bands.items():
                row = scores[(sid, cid)]
                assert row["band"] == reference, (
                    f"{submission.submission_id}/{cid} scored {row['band']!r} against the "
                    f"corpus's reference band {reference!r} - the run replayed a recording "
                    "that does not belong to this cell")

        for index in world.sid_by_index:
            sid = world.sid_by_index[index]
            assert scores[(sid, "C2")]["judge_count"] == 5, (
                "C2's (2,4,4) panel must escalate: three panel arms plus the ladder's two "
                f"extension arms, got {scores[(sid, 'C2')]['judge_count']}")
            assert scores[(sid, "C3")]["judge_count"] == 0, (
                "the mcq criterion is scored by M-DET, not by a panel")
    finally:
        world.store.close()


def test_f_dev_pipe_c2_escalates_on_the_band_its_panel_settles(tmp_path, monkeypatch) -> None:
    """The honest form of §4.4's `(2,4,4)` claim, asserted on `should_escalate`'s reasons.

    `judge_count == 5` cannot carry this: every judged cell of the corpus escalates, so the
    count is satisfied by a unanimous panel too (measured — see `dev_pipe.ESCALATION_ORDINALS`).
    The reasons discriminate. `C2`'s panel settles on `secure`, ordinal 4 of 6 and therefore
    interior, and `interior band position` is the limb that reads exactly that. Move the panel
    to an edge and this fails while the count assertion would not.

    Spying on the module-level name rather than on a collaborator: `aggregate_walk` calls
    `should_escalate` through `tests.support.e2e_world`'s import, which is the seam a spy can
    reach without changing the drive.
    """
    import tests.support.e2e_world as world_module

    real = world_module.should_escalate
    reasons_by_criterion: dict[str, set[str]] = {}

    def spy(**kwargs):
        decision = real(**kwargs)
        reasons_by_criterion.setdefault(
            kwargs["criterion"].criterion_id, set()
        ).update(decision.reasons)
        return decision

    monkeypatch.setattr(world_module, "should_escalate", spy)

    world = replay_world(tmp_path / "data")
    try:
        drive_full_run(world)
    finally:
        world.store.close()

    assert "C2" in reasons_by_criterion, (
        "should_escalate was never asked about C2 - the aggregation walk did not reach it")
    assert "interior band position" in reasons_by_criterion["C2"], (
        f"C2's panel settles on a band that is not interior, so the limb §4.4's (2,4,4) is "
        f"meant to fire never fired. Reasons seen: {sorted(reasons_by_criterion['C2'])}")


# --- F-DEV-PIPE-TWO-RUN ---------------------------------------------------------------------


def test_f_dev_pipe_two_run_sets_answer_identical_requests_with_different_bands() -> None:
    """Why the two sets are two directories, asserted on the committed bytes.

    A judge request is keyed on the assembled prompt — directive, criterion, bands, then the
    submission and its extracted evidence. No run identifier appears in it, and the two runs
    share submissions and extraction, so run A's verdict and run B's verdict are answers to a
    byte-identical request. This case pins that: the judge recordings SHARE their keys across
    the sets and differ only in the completion. One directory could not hold both, and a future
    change that tried to merge them would fail here rather than silently dropping half.
    """
    a, b = (
        {p.name: json.loads(p.read_text(encoding="utf-8"))
         for p in sorted(two_run_dir(run).glob("*.json"))}
        for run in ("run-a", "run-b")
    )
    assert a and b, "both two-run recording sets must be committed"

    judge_keys = {
        name for name, doc in a.items()
        if doc["request"]["model_ref"]["role"] == "judge"
    }
    assert judge_keys <= set(b), (
        "a judge request recorded in run-a has no counterpart key in run-b - the two sets are "
        "supposed to answer the SAME requests")
    shared = sorted(k for k in judge_keys if a[k]["completion"] == b[k]["completion"])
    assert shared == [], (
        f"{len(shared)} of {len(judge_keys)} judge recordings carry the SAME completion in "
        f"both sets, so those cells cannot tell the two runs apart: {shared[:3]}")


@pytest.mark.parametrize("run", ["run-a", "run-b"])
def test_f_dev_pipe_two_run_each_set_replays_a_full_run(run, tmp_path) -> None:
    """Each set drives the whole pipeline from committed bytes with nothing recorded.

    The band assertion is the discriminating half: `run-a` must land every judged criterion on
    `minimal` and `run-b` on `developing` — §4.4's `(1,1,1)` and `(3,3,3)`. A world pointed at
    one set while expecting the other's bands fails inside the drive.
    """
    expected = dev_pipe.band_at("C1", dev_pipe.TWO_RUN_ORDINALS[run])
    world = two_run_replay_world(tmp_path / "data", run)
    try:
        drive_full_run(world)
        assert world.provider.misses == [], (
            f"{run} has requests with no recording: {world.provider.misses}")
        judged = {
            (row["submission_id"], row["criterion_id"]): row["band"]
            for row in world.handle.query(
                "SELECT submission_id, criterion_id, band FROM criterion_score "
                "WHERE criterion_id IN ('C1', 'C2')"
            )
        }
        assert len(judged) == 6, f"expected 3 submissions x 2 judged criteria, got {len(judged)}"
        assert set(judged.values()) == {expected}, (
            f"{run}'s judged cells must all settle on {expected!r} - a unanimous panel at one "
            f"ordinal is what (1,1,1) and (3,3,3) mean. Got {sorted(set(judged.values()))}")
    finally:
        world.store.close()


def test_f_dev_pipe_two_run_drives_both_runs_in_one_store(tmp_path) -> None:
    """The shape the isolation cases need: one cohort, one ingest, two runs, different bands.

    TC-GRADE-25 and ADV-13 ask whether run B's figures can leak into run A's grades, queue,
    stats or console. Neither can be written unless two runs can coexist in one store with
    recognisably different judged bands — that is what this asserts, and it is the reason the
    corpus exists at all rather than being two unrelated fixtures.

    The scores are read back per run: every judged cell of A sits at `minimal`, every judged
    cell of B at `developing`, in the same `criterion_score` table. The MCQ criterion is
    identical in both by design — `M-DET` scores it from the selection mark, so it is not a
    judged criterion and §4.4's "differ on every judged criterion" does not reach it.
    """
    world = two_run_replay_world(tmp_path / "data", "run-a")
    try:
        drive_full_run(world)
        run_a = world.run_id
        assert world.provider.misses == []

        run_b = drive_second_run(world, "run-b")
        assert world.provider.misses == [], (
            f"the second run has requests with no recording: {world.provider.misses}")
        assert run_b != run_a, "the second run must have its own run id"

        by_run: dict[str, set[str]] = {}
        for row in world.handle.query(
            "SELECT run_id, band FROM criterion_score WHERE criterion_id IN ('C1', 'C2')"
        ):
            by_run.setdefault(row["run_id"], set()).add(row["band"])

        assert set(by_run) == {run_a, run_b}, (
            f"both runs must have their own criterion_score rows, found {sorted(by_run)}")
        assert by_run[run_a] == {dev_pipe.band_at("C1", dev_pipe.TWO_RUN_ORDINALS["run-a"])}
        assert by_run[run_b] == {dev_pipe.band_at("C1", dev_pipe.TWO_RUN_ORDINALS["run-b"])}
        assert by_run[run_a] != by_run[run_b], (
            "the two runs settled on the same bands, so no isolation case built on this corpus "
            "could tell a leak from correct behaviour")
    finally:
        world.store.close()
