def test_the_refusal_sentences_are_the_design_tables() -> None:
    """§4.3's exact-match property, at the corpus level: the refusal table cannot drift.

    FR-AUTHOR-28's sentences are the teacher-facing copy — the design delta states them
    verbatim so "Save this as one of those" is not paraphrased into "Export it as a supported
    format" by a refactor. Each fixture-backed arm's `expected.toml` must carry the exact
    sentence `DESIGN_REFUSAL_TABLE` pins (the dict above is the design-table copy).
    """
    for af_id, sentence in DESIGN_REFUSAL_TABLE.items():
        if af_id.startswith("AF-"):
            data = tomllib.loads((CORPUS / af_id / "expected.toml").read_text(encoding="utf-8"))
            assert data.get("refusal") == sentence, (
                f"{CASE}: {af_id}'s refusal sentence has drifted from the design table:\n"
                f"  corpus: {data.get('refusal')!r}\n  design: {sentence!r}"
            )


