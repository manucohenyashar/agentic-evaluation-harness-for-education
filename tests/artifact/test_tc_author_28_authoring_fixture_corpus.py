"""`TC-AUTHOR-28` — the authoring fixture corpus exists, is honest, and rebuilds byte-identical.

Case: test plan §5.6, `FR-PROV-10`, `TS-153` (#686). Oracle: **census + recording inspection**
(`§4.2`'s double-honesty rule). This file is the census's corpus half; the recordings half —
the one that stays writtenahead-red until the capture pass runs — is
`test_tc_author_28_recordings_honesty.py` beside it.

    | Census of `fixtures/F-AUTHOR/`: 13 fixture dirs + `expected.toml` each, recordings under
    | `recordings/`; recordings produced via the record path; corpus reproduces the fallback
    | (failing head of chain) and placeholder paths |

**Level.** §5.6 specifies rung 0 — an assertion about committed bytes, which is what §4.3
calls an artifact assertion. It lives in `tests/artifact/` and runs in the fast tier, the
same disposition `TC-CONFORM-01`'s census got (that file's docstring records why rung 2 is
"not achievable and not meaningful" for a corpus census).

**Green, and that is not a mistake.** The issue is written ahead of M-AUTHOR, but the corpus
is this story's *deliverable*: the census asserts the corpus is what the design delta §5.1
requires of it, and a red one would mean the corpus is wrong rather than that the code is
missing. The recordings half carries the red — see the honesty file's docstring for why a
green recording tree would be the lie.

**Reproducibility here, not in `--check`.** `F-AUTHOR/` is generated by a committed generator
*inside* the corpus (`fixtures/F-AUTHOR/build_authoring_fixtures.py`, the design delta §5.1
`build_sample_materials.py` pattern), not by `harness/corpora/` — so
`python -m harness.corpora.build --check` exempts the whole tree
(`_IN_TREE_GENERATED_TREES`). The exemption would make the tree archaeology, so the same
mechanism is re-pointed here: rebuild into a temp directory and byte-diff against the
committed tree. A hand edit fails this file the way a hand edit in any other corpus fails
`test_corpora_are_reproducible.py`.

Also carries the regression for the scan-glyph bug the corpus's construction found: glyph
`"6"` in `harness.corpora.scan._GLYPHS` was malformed (its stroke tuple collapsed), so any
`render_hand_page` text containing a 6 crashed. Every F-SCAN text happens to lack a 6, so the
bug lay dormant until AF-10's scanned test description needed digits. Rendered determinism is
asserted alongside, since a glyph table edit that changed committed scan bytes elsewhere
would resurface as a `--check` diff in F-SCAN.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
CORPUS = REPO_ROOT / "fixtures" / "F-AUTHOR"
GENERATOR = CORPUS / "build_authoring_fixtures.py"

EXPECTED_AF_IDS = [f"AF-{i:02d}" for i in range(1, 14)]
OUTCOME_DOMAIN = {"resolved", "partial", "unresolved"}
BUILD_DOMAIN = {"publishes", "refused"}

CASE = "TC-AUTHOR-28"


def test_the_thirteen_fixture_dirs_exist() -> None:
    missing = [af for af in EXPECTED_AF_IDS if not (CORPUS / af / "expected.toml").is_file()]
    assert not missing, (
        f"{CASE}: the authoring fixture corpus is incomplete — "
        f"{missing} have no expected.toml under {CORPUS}. "
        f"Rebuild with `python fixtures/F-AUTHOR/build_authoring_fixtures.py`."
    )


@pytest.mark.parametrize("af_id", EXPECTED_AF_IDS)
def test_every_expected_toml_is_schema_valid(af_id: str) -> None:
    """Each fixture's outcome classes are loadable and inside the declared domains.

    The `expected.toml` schema is this corpus's own convention (documented in the corpus
    README): `af`, `description`, `documents`, `outcome`, `placeholders`, `build`, plus the
    re-draft pair `retry_of`/`carry_over` on AF-13. The census checks the schema, not the
    values — the values are asserted by the per-fixture outcome tests (#703, #702's tier),
    against whatever the recorded and live tiers actually produce.
    """
    path = CORPUS / af_id / "expected.toml"
    data = tomllib.loads(path.read_text(encoding="utf-8"))

    assert data["af"] == af_id, (
        f"{CASE}: {path.name} declares af={data['af']!r} but sits in the {af_id!r} directory"
    )
    assert isinstance(data["description"], str) and data["description"], (
        f"{CASE}: {path.name} has no description"
    )
    assert data["outcome"] in OUTCOME_DOMAIN, (
        f"{CASE}: {path.name} outcome {data['outcome']!r} outside {sorted(OUTCOME_DOMAIN)}"
    )
    assert data["build"] in BUILD_DOMAIN, (
        f"{CASE}: {path.name} build {data['build']!r} outside {sorted(BUILD_DOMAIN)}"
    )
    documents = data["documents"]
    assert isinstance(documents, list) and documents, (
        f"{CASE}: {path.name} lists no documents"
    )
    for name in documents:
        assert (CORPUS / af_id / name).is_file(), (
            f"{CASE}: {path.name} names document {name!r} that does not exist in {af_id}/"
        )
    assert isinstance(data.get("placeholders", []), list), (
        f"{CASE}: {path.name} placeholders is not a list"
    )
    if "retry_of" in data:
        assert data["retry_of"] in EXPECTED_AF_IDS, (
            f"{CASE}: {path.name} retry_of={data['retry_of']!r} names no fixture in the corpus"
        )


def test_af_13_is_the_only_re_draft() -> None:
    """The re-draft flow has exactly one fixture, and AF-13's retry_of names AF-01."""
    retries = {
        af: tomllib.loads((CORPUS / af / "expected.toml").read_text(encoding="utf-8")).get("retry_of")
        for af in EXPECTED_AF_IDS
    }
    named = {af: r for af, r in retries.items() if r is not None}
    assert named == {"AF-13": "AF-01"}, (
        f"{CASE}: only AF-13 is the re-draft fixture (retry_of=AF-01); found {named}"
    )


def test_the_corpus_readmes_state_the_conventions() -> None:
    corpus_readme = (CORPUS / "README.md").read_text(encoding="utf-8")
    recordings_readme = (CORPUS / "recordings" / "README.md").read_text(encoding="utf-8")
    for needle in ("expected.toml", "build_authoring_fixtures.py"):
        assert needle in corpus_readme, (
            f"{CASE}: the corpus README does not mention {needle!r} — "
            f"a reader cannot reconstruct the corpus conventions from the corpus itself"
        )
    for needle in ("coverage.json", "aeh.prov/fixture/1"):
        assert needle in recordings_readme, (
            f"{CASE}: the recordings README does not mention {needle!r} — "
            f"a reader cannot reconstruct the recordings convention from the corpus itself"
        )


def test_the_corpus_rebuilds_byte_identical() -> None:
    """The pin that replaces `--check`: re-run the in-tree generator, byte-diff.

    `harness.corpora.build.check` cannot do this — its generators live under
    `harness/corpora/` and this corpus's lives in the corpus — so the same mechanism is
    driven here against the in-tree generator. Any committed byte that the generator does
    not reproduce fails here, naming the file.
    """
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "F-AUTHOR"
        result = subprocess.run(
            [sys.executable, "-I", "-c",
             "import sys; sys.dont_write_bytecode = True;"
             f"sys.path.insert(0, {str(GENERATOR.parent)!r});"
             "import pathlib;"
             "import build_authoring_fixtures as g;"
             f"g.build(pathlib.Path({str(out)!r}))"],
            cwd=REPO_ROOT, capture_output=True, text=True,
        )
        assert result.returncode == 0, (
            f"{CASE}: rebuilding the corpus failed: {result.stderr.strip()}"
        )

        def tree(root: Path) -> dict[str, bytes]:
            return {
                p.relative_to(root).as_posix(): p.read_bytes()
                for p in sorted(root.rglob("*")) if p.is_file()
            }

        fresh, committed = tree(out), tree(CORPUS)
        # The generator lives inside the corpus but is not one of its outputs — the temp
        # rebuild cannot emit it, and a diff that fired on the generator itself would fire
        # on its own checkout. `__pycache__` is not corpus data either. Under
        # `recordings/`, only `recordings/README.md` is generated; the `sha256-*.json` and
        # `coverage.json` files are *captured* (#690's pass), not emitted — exempting them
        # here is what lets the landing PR that captures them keep this unmarked census
        # green, with the honesty file beside this one pinning the captured half.
        #
        # Disclosed reconcile (the landing): `recordings-af01-variant/` is the same story's
        # second captured set (TC-AUTHOR-29's AF-01 variant replies, landed by the same
        # #690 pass into the path `tests/support/author_vocabulary.py` declares) — captured,
        # not emitted, so the whole directory is exempt like `recordings/`'s captured half.
        committed.pop(GENERATOR.name, None)
        committed = {
            p: b for p, b in committed.items()
            if "__pycache__" not in p
            and not (p.startswith("recordings/") and p != "recordings/README.md")
            and not p.startswith("recordings-af01-variant/")
        }
        stale = sorted(
            path for path in committed.keys() | fresh.keys()
            if committed.get(path) != fresh.get(path)
        )
        assert not stale, (
            f"{CASE}: {stale} differ from what the generator emits. "
            f"Rebuild with `python fixtures/F-AUTHOR/build_authoring_fixtures.py` — "
            f"a hand edit makes the corpus archaeology."
        )


def test_scan_glyph_6_renders_deterministically() -> None:
    """Regression: `render_hand_page` crashed on any text containing a 6.

    `_GLYPHS["6"]`'s stroke tuple had collapsed (`((...))` rather than `((...),)`), so the
    renderer read the glyph's *points* as *strokes* and tried to unpack a float as a
    coordinate pair. F-SCAN's committed texts contain no 6, so the bug stayed latent until
    AF-10's scanned test description needed digits. Assert both that it renders and that the
    same seed renders identical bytes — a glyph-table edit that changed committed scan bytes
    would otherwise surface only as a distant `--check` diff in F-SCAN.
    """
    import random

    from harness.corpora import scan

    first = scan.render_hand_page(
        "6 16 60 2026", legibility="legible", rng=random.Random(1))
    second = scan.render_hand_page(
        "6 16 60 2026", legibility="legible", rng=random.Random(1))
    assert len(first) > 0 and first == second, (
        f"{CASE}: render_hand_page with a 6 in the text is broken or non-deterministic"
    )