@pytest.mark.parametrize("af_id", EXPECTED_AF_IDS)
def test_every_expected_toml_is_schema_valid(af_id: str) -> None:
    """Each fixture's outcome classes are loadable and inside the declared domains.

    The `expected.toml` schema is this corpus's own convention (documented in the corpus
    README): `af`, `description`, `documents`, `outcome`, `placeholders`, `build`, the
    re-draft pair `retry_of`/`carry_over` on AF-13, and — since #753 — the intake keys
    `refusal`, `warnings`, `format` and `table_rows`. The census checks the schema, not the
    values — the values are asserted by the per-fixture outcome tests (#703, #702's tier;
    the intake fixtures' by `test_tc_author_32_38_intake_fixtures.py`, blocked on #754),
    against whatever the recorded and live tiers actually produce.
    """
    path = CORPUS / af_id / "expected.toml"
    data = tomllib.loads(path.read_text(encoding="utf-8"))

    assert data["af"] == af_id, (
        f"{CASE}: {path.name} declares af={data['af']!r} but sits in the {af_id!r} directory"
    )
    assert isinstance(data["description"], str) and data["description"], (
        f"{CASE}: {path.name} has no description"
    )
    assert data["outcome"] in OUTCOME_DOMAIN, (
        f"{CASE}: {path.name} outcome {data['outcome']!r} outside {sorted(OUTCOME_DOMAIN)}"
    )
    assert data["build"] in BUILD_DOMAIN, (
        f"{CASE}: {path.name} build {data['build']!r} outside {sorted(BUILD_DOMAIN)}"
    )
    documents = data["documents"]
    assert isinstance(documents, list) and documents, (
        f"{CASE}: {path.name} lists no documents"
    )
    for name in documents:
        assert (CORPUS / af_id / name).is_file(), (
            f"{CASE}: {path.name} names document {name!r} that does not exist in {af_id}/"
        )
    assert isinstance(data.get("placeholders", []), list), (
        f"{CASE}: {path.name} placeholders is not a list"
    )
    if "retry_of" in data:
        assert data["retry_of"] in EXPECTED_AF_IDS, (
            f"{CASE}: {path.name} retry_of={data['retry_of']!r} names no fixture in the corpus"
        )
    # -- the intake keys (#753) --------------------------------------------------------
    refusal = data.get("refusal")
    if data["outcome"] == "refused":
        assert data["build"] == "refused", (
            f"{CASE}: {path.name} outcome=refused but build={data['build']!r} — an intake "
            f"refusal never publishes"
        )
        assert isinstance(refusal, str) and refusal, (
            f"{CASE}: {path.name} refuses but carries no FR-AUTHOR-28 refusal sentence"
        )
        assert "review" not in data, (
            f"{CASE}: {path.name} refuses at intake, so no draft exists for a review walk"
        )
    else:
        assert refusal is None, (
            f"{CASE}: {path.name} is not refused but carries a refusal sentence"
        )
    for code in data.get("warnings", []):
        assert code in WARNING_CODE_DOMAIN, (
            f"{CASE}: {path.name} warning {code!r} outside {sorted(WARNING_CODE_DOMAIN)}"
        )
    formats = data.get("format")
    if formats is not None:
        assert isinstance(formats, list) and len(formats) == len(documents), (
            f"{CASE}: {path.name} format {formats!r} does not align with its documents"
        )
        for source_format in formats:
            assert source_format in SOURCE_FORMAT_DOMAIN, (
                f"{CASE}: {path.name} format {source_format!r} outside "
                f"{sorted(SOURCE_FORMAT_DOMAIN)}"
            )
    table_rows = data.get("table_rows")
    if table_rows is not None:
        assert isinstance(table_rows, list) and table_rows and all(
            isinstance(row, list) and row and all(isinstance(cell, str) for cell in row)
            for row in table_rows
        ), f"{CASE}: {path.name} table_rows is not a non-empty table of string rows"


