def test_af21_carries_af14s_text_as_a_txt_twin() -> None:
    """AF-21's third document is AF-14's content re-encoded as .txt — by construction.

    The generator derives the twin from the same content model that renders AF-14's .docx
    (`blocks_to_plain_text(AF14_BLOCKS)`), which is what makes the cross-format pair
    content-identical rather than approximately similar — the property TC-AUTHOR-32's
    format-independence and TC-AUTHOR-38's carry-over journey stand on. Asserted against the
    committed bytes here, so a content-model edit that changes only one side fails.
    """
    import importlib.util

    spec = importlib.util.spec_from_file_location("build_authoring_fixtures", GENERATOR)
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)

    af21 = tomllib.loads((CORPUS / "AF-21" / "expected.toml").read_text(encoding="utf-8"))
    twin_name = "hist7-rome-01-test-and-grading.txt"
    assert twin_name in af21["documents"] and af21["format"][-1] == "txt", (
        f"{CASE}: AF-21 no longer declares the {twin_name} twin"
    )
    twin = (CORPUS / "AF-21" / twin_name).read_text(encoding="utf-8")
    assert twin == generator.blocks_to_plain_text(generator.AF14_BLOCKS), (
        f"{CASE}: the {twin_name} twin is not AF-14's content model rendered as .txt — "
        f"the cross-format pair is no longer content-identical"
    )


def test_the_corpus_rebuilds_byte_identical() -> None:
    """The pin that replaces `--check`: re-run the in-tree generator, byte-diff.

    `harness.corpora.build.check` cannot do this — its generators live under
    `harness/corpora/` and this corpus's lives in the corpus — so the same mechanism is
    driven here against the in-tree generator. Any committed byte that the generator does
    not reproduce fails here, naming the file.
    """
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "F-AUTHOR"
        result = subprocess.run(
            [sys.executable, "-I", "-c",
             "import sys; sys.dont_write_bytecode = True;"
             f"sys.path.insert(0, {str(GENERATOR.parent)!r});"
             "import pathlib;"
             "import build_authoring_fixtures as g;"
             f"g.build(pathlib.Path({str(out)!r}))"],
            cwd=REPO_ROOT, capture_output=True, text=True,
        )
        assert result.returncode == 0, (
            f"{CASE}: rebuilding the corpus failed: {result.stderr.strip()}"
        )

        def tree(root: Path) -> dict[str, bytes]:
            return {
                p.relative_to(root).as_posix(): p.read_bytes()
                for p in sorted(root.rglob("*")) if p.is_file()
            }

        fresh, committed = tree(out), tree(CORPUS)
        # The generator lives inside the corpus but is not one of its outputs — the temp
        # rebuild cannot emit it, and a diff that fired on the generator itself would fire
        # on its own checkout. `__pycache__` is not corpus data either. Under
        # `recordings/`, only `recordings/README.md` is generated; the `sha256-*.json` and
        # `coverage.json` files are *captured* (#690's pass), not emitted — exempting them
        # here is what lets the landing PR that captures them keep this unmarked census
        # green, with the honesty file beside this one pinning the captured half.
        #
        # Disclosed reconcile (the landing): `recordings-af01-variant/` is the same story's
        # second captured set (TC-AUTHOR-29's AF-01 variant replies, landed by the same
        # #690 pass into the path `tests/support/author_vocabulary.py` declares) — captured,
        # not emitted, so the whole directory is exempt like `recordings/`'s captured half.
        committed.pop(GENERATOR.name, None)
        committed = {
            p: b for p, b in committed.items()
            if "__pycache__" not in p
            and not (p.startswith("recordings/") and p != "recordings/README.md")
            and not p.startswith("recordings-af01-variant/")
        }
        stale = sorted(
            path for path in committed.keys() | fresh.keys()
            if committed.get(path) != fresh.get(path)
        )
        assert not stale, (
            f"{CASE}: {stale} differ from what the generator emits. "
            f"Rebuild with `python fixtures/F-AUTHOR/build_authoring_fixtures.py` — "
            f"a hand edit makes the corpus archaeology."
        )


def test_scan_glyph_6_renders_deterministically() -> None:
    """Regression: `render_hand_page` crashed on any text containing a 6.

    `_GLYPHS["6"]`'s stroke tuple had collapsed (`((...))` rather than `((...),)`), so the
    renderer read the glyph's *points* as *strokes* and tried to unpack a float as a
    coordinate pair. F-SCAN's committed texts contain no 6, so the bug stayed latent until
    AF-10's scanned test description needed digits. Assert both that it renders and that the
    same seed renders identical bytes — a glyph-table edit that changed committed scan bytes
    would otherwise surface only as a distant `--check` diff in F-SCAN.
    """
    import random

    from harness.corpora import scan

    first = scan.render_hand_page(
        "6 16 60 2026", legibility="legible", rng=random.Random(1))
    second = scan.render_hand_page(
        "6 16 60 2026", legibility="legible", rng=random.Random(1))
    assert len(first) > 0 and first == second, (
        f"{CASE}: render_hand_page with a 6 in the text is broken or non-deterministic"
    )