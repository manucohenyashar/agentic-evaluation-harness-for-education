#: sha256 over `"<version>:<name>\n"` then each statement's text plus a newline, for Cohort
#: migrations 1..27. Measured equal at `fb12d1e` (whose chain ends at 27) and at #445's HEAD.
COHORT_27_MIGRATIONS_SHA256 = "7a3c6b0353d90e6559d6534f71189f3a4d19a175e0267e4330b631df8430b205"
COHORT_PRE_DELTA_VERSION = 27

#: F-JEV / F-JEV-WIRE name backends by deployment (`harness` may not name a provider,
#: CT-PROV-15); this is the mapping to `ModelRef.provider`.
BACKEND_PROVIDER = {"cloud": "openrouter-jev", "edge": "openjev"}


def _read(corpus: str, relative: str) -> Any:
    return json.loads((CORPUS_ROOT / corpus / relative).read_text(encoding="utf-8"))


# --- F-JEV-WIRE ----------------------------------------------------------------------------------

def wire_request(name: str = "canonical") -> DecisionRequest:
    """The `DecisionRequest` an F-JEV-WIRE body answers (`entry["request"]`)."""
    spec = jev.WIRE_REQUESTS[name]
    questions = []
    for key, q in spec["questions"].items():
        if q["type"] == "choice":
            questions.append(ChoiceQuestion(key, q["instructions"], tuple(q["options"].items())))
        elif q["type"] == "score":
            questions.append(ScoreQuestion(key, q["instructions"], tuple(q["levels"])))
        else:
            questions.append(NoulQuestion(key, q["instructions"]))
    return DecisionRequest(state=spec["state"], questions=tuple(questions))


def wire_bodies() -> tuple[dict[str, Any], ...]:
    """Every committed F-JEV-WIRE entry, in manifest order."""
    manifest = _read("F-JEV-WIRE", "manifest.json")
    return tuple(_read("F-JEV-WIRE", e["path"]) for e in manifest["submissions"])


# --- F-JEV ---------------------------------------------------------------------------------------

def _cells() -> tuple[dict[str, Any], ...]:
    manifest = _read("F-JEV", "manifest.json")
    return tuple(_read("F-JEV", e["path"]) for e in manifest["submissions"])


def _scoring_request(cell: dict[str, Any], criteria: dict[str, Any]) -> ScoringRequest:
    crit = criteria[cell["criterion_id"]]
    return ScoringRequest(
        work_id=cell["cell_id"],
        criterion={"criterion_id": cell["criterion_id"], "text": crit["text"],
                   "bands": [{"band": b, "ordinal": i, "descriptor": d}
                             for i, (b, d) in enumerate(crit["bands"])],
                   "exemplars": []},
        question={"prompt_text": "A crate rests on a ramp. Explain why it does not slide.",
                  "reference_solution": "Friction balances the component of weight."},
        evidence=cell["spans"], dependency_evidence=[],
        submission={"submission_id": cell["cell_id"], "student_ref": f"ref-{cell['cell_id']}"},
        submission_text=cell["submission_text"])


def f_jev_requests() -> dict[str, tuple[dict[str, Any], ScoringRequest]]:
    """`{cell_id: (cell, ScoringRequest)}` for F-JEV's 40 cells."""
    criteria = _read("F-JEV", "manifest.json")["criteria"]
    return {c["cell_id"]: (c, _scoring_request(c, criteria)) for c in _cells()}


def answer_document(request: DecisionRequest, answer: dict[str, Any], model: str) -> dict[str, Any]:
    """One cell's recorded figures as the §1.2 response to `request`."""
    answers: dict[str, Any] = {}
    for q in request.questions:
        if isinstance(q, ScoreQuestion):
            probs = answer["band_probabilities"]
            # Design 1.8: a Jev build reports its own Score confidence, and the harness never
            # derives one. The recorded value is numerically what 1.6 derived from these
            # probabilities, so every hand count over F-JEV (24/40 accepted, 8/40 divergent) holds.
            answers[q.key] = {"type": "score", "score": round(sum(i * p for i, p in enumerate(probs)), 6),
                              "probabilities": {str(i): p for i, p in enumerate(probs)},
                              "legend": {str(i): lvl for i, lvl in enumerate(q.levels)},
                              "confidence": derived_confidence(probs)}
        elif q.key == "evidence_sufficient":
            answers[q.key] = {"type": "noul", "noul": answer["sufficiency"]}
        else:
            answers[q.key] = {"type": "noul", "noul": answer["cites"][q.key[len("cite_"):]]}
    return {"model": model, "answers": answers, "usage": {"input_tokens": 100, "output_tokens": 0}}


def record_f_jev(fixture_dir: Path, backend: str, engine: Any) -> dict[str, DecisionRequest]:
    """Record every F-JEV cell's `backend` answer as a `decide` fixture for `engine.model`.
    Returns `{cell_id: DecisionRequest}`."""
    provider = RecordedFixtureProvider(fixture_dir=fixture_dir)
    out = {}
    for cell_id, (cell, request) in f_jev_requests().items():
        decision = decision_request(request, engine)
        provider.record_decision(decision, engine.model,
                                 answer_document(decision, cell["answers"][backend], backend))
        out[cell_id] = decision
    return out


# --- F-ADV-INJ-DECISION: TC-JUDGE-43's recorded answers -----------------------------------------

def adv_decision_requests() -> dict[str, tuple[dict[str, Any], ScoringRequest]]:
    """`{member_id: (manifest member, ScoringRequest)}` for the 8 twin members: criterion C-01,
    the first page as the submission, and the first two Q1 lines as the two real spans."""
    from harness.corpora import reference_package

    manifest = _read("F-ADV-INJ-DECISION", "manifest.json")
    criterion = reference_package.BY_ID[manifest["decision_answers"]["criterion_id"]]
    out = {}
    for member in manifest["submissions"]:
        document = (CORPUS_ROOT / "F-ADV-INJ-DECISION" / member["path"]).read_text(encoding="utf-8")
        page = document.split("<!-- page: 1 of 2 -->\n", 1)[1].split("\n\n<!-- page: 2", 1)[0]
        lines = [ln for ln in page.split("\n## Q1\n\n", 1)[1].split("\n") if ln.strip()][:2]
        spans, cursor = [], 0
        for line in lines:
            start = page.index(line, cursor)
            spans.append({"start": start, "end": start + len(line), "text": line,
                          "region_kind": "transcribed_text"})
            cursor = start + len(line)
        request = ScoringRequest(
            work_id=member["id"],
            criterion={"criterion_id": criterion.criterion_id, "text": criterion.text,
                       "bands": [{"band": b.band, "ordinal": b.ordinal, "descriptor": b.descriptor}
                                 for b in criterion.bands], "exemplars": []},
            question={"prompt_text": "Draw and label the forces on the crate.",
                      "reference_solution": "Weight, normal force and friction."},
            evidence=spans, dependency_evidence=[],
            submission={"submission_id": member["id"], "student_ref": member["student_ref"]},
            submission_text=page)
        out[member["id"]] = (member, request)
    return out


def record_adv_decisions(fixture_dir: Path, engine: Any) -> dict[str, tuple[dict, ScoringRequest, DecisionRequest]]:
    """Record F-ADV-INJ-DECISION's declared answers as `decide` fixtures for `engine.model`."""
    from harness.corpora import reference_package

    answers = _read("F-ADV-INJ-DECISION", "manifest.json")["decision_answers"]
    criterion = reference_package.BY_ID[answers["criterion_id"]]
    n = len(criterion.bands)
    provider = RecordedFixtureProvider(fixture_dir=fixture_dir)
    out = {}
    for member_id, (member, scoring) in adv_decision_requests().items():
        spec = answers[member["variant"]]
        if spec["band"] == "top":
            peak_at = n - 1
        else:
            peak_at = next(b.ordinal for b in criterion.bands
                           if b.band == member["reference_bands"][answers["criterion_id"]])
        probs = [(1.0 - spec["probability"]) / (n - 1)] * n
        probs[peak_at] = spec["probability"]
        figures = {"band_probabilities": probs, "sufficiency": answers["sufficiency"],
                   "cites": {"a": answers["cite"], "b": answers["cite"]}}
        request = decision_request(scoring, engine)
        provider.record_decision(request, engine.model, answer_document(request, figures, "fixture"))
        out[member_id] = (member, scoring, request)
    return out


# --- F-STATS-JEV ---------------------------------------------------------------------------------

def stats_labels(subset: str | None = None) -> tuple[SimpleNamespace, ...]:
    """F-STATS-JEV's labels as attribute objects (`label_type`, `evaluation_mode`,
    `saw_system_output`, `system_band`, `teacher_band`, …), optionally one named subset."""
    rows = _read("F-STATS-JEV", "labels.json")
    return tuple(SimpleNamespace(**r) for r in rows if subset is None or subset in r["subsets"])


def partition_of(label: Any) -> str:
    """The engine partition a label declares: the resolver `agreement_by_engine` takes."""
    return label.partition


# --- F-SCHEMA: the Cohort-27 database ------------------------------------------------------------

def cohort_27_migrations_digest() -> str:
    h = hashlib.sha256()
    for m in TIER_MIGRATIONS[Tier.COHORT]:
        if m.version > COHORT_PRE_DELTA_VERSION:
            continue
        h.update(f"{m.version}:{m.name}\n".encode())
        for statement in m.statements:
            h.update(str(statement).encode() + b"\n")
    return h.hexdigest()


def cohort_27_database(db_path: Path) -> Path:
    """A Cohort database at schema version 27 with pre-delta verdict rows (no
    `scoring_engine` column, no `decision_prescreen` table): what `fb12d1e` wrote."""
    digest = cohort_27_migrations_digest()
    assert digest == COHORT_27_MIGRATIONS_SHA256, (
        f"Cohort migrations 1..27 no longer match their text at fb12d1e ({digest}); migrations are "
        "append-only, so a shipped migration was edited. The Cohort-27 database would not be "
        "the one fb12d1e wrote.")
    from tests.integration.store.test_migrations import _fixture_database

    _fixture_database(db_path, Tier.COHORT, COHORT_PRE_DELTA_VERSION)
    return db_path
