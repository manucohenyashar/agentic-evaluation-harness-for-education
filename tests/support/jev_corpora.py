"""Loaders for the Jev corpora (#445): the half of each corpus that needs `aeh` to use.

The data is generated by `harness/corpora/jev.py`, or captured by `tests/support/pipe_world.py`
in F-JEV-DECISIONS' case. This module turns it into the objects the consuming cases take, and
it builds F-SCHEMA's Cohort-27 database.

- `wire_request(name)` / `wire_bodies()`: F-JEV-WIRE's requests and bodies, for a programmed
  `Transport`.
- `f_jev_requests()` / `record_f_jev(...)`: F-JEV's cells as `ScoringRequest`s, and their
  per-backend answers recorded as `decide` fixtures. They are keyed by the shipped
  `judge.decision_request`, so the keys follow the request builder rather than being frozen
  beside it.
- `stats_labels()` / `partition_of`: F-STATS-JEV's labels in the attribute shape `aeh.stats`
  reads.
- `cohort_27_database(path)`: F-SCHEMA's pre-delta Cohort database at version 27. The plan
  says "generated by checking out fb12d1e". Migrations are append-only, so the text of Cohort
  migrations 1..27 today is exactly fb12d1e's whole Cohort chain. That was measured, and it
  is pinned below as `COHORT_27_MIGRATIONS_SHA256`. The database is built from that text by
  the builder TC-STORE-04 already uses, so a change to any migration at or below 27 fails
  here instead of silently producing a different "version 27".
"""

