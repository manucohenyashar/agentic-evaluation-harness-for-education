"""`FUZZ-07` — the blob store and the write queue. Test plan §6.7, TS-56 (issue #149).

| Target | Invariant |
|---|---|
| `FR-STORE-06` | `get(put(b)) == b`; `path()` always resolves inside the data directory |
| `FR-STORE-04` | The result-plus-status atomicity invariant holds for every interleaving |

**Split into two tests, keyed on two blockers.** The blob store is #12 and the write queue is #11;
both depend on #10 and neither depends on the other, so they become runnable at different moments
and keying the case as one would hold whichever landed first outside the gate.

**The atomicity case aborts transactions, and its first draft did not.** Every generated
transaction ran to completion, so both writes always landed and the invariant was trivially true —
review proved it by dropping in a `transaction()` that is a bare `yield`, with no BEGIN, no COMMIT,
no rollback and two independent autocommit writes, and watching 500/500 examples pass.
`CT-STORE-03`'s claim is "both present or both absent **after any crash**", and a corpus with no
crash in it tests the half nobody doubted. The generated interleaving now carries an outcome per
transaction, and `test_fuzz_generators.py` asserts aborts actually appear in it.

**The keys close the window rather than narrowing it.** `blocker_is_resolved`'s `symbol` kind
checks that a name *exists*, and design §3.3 declares `Store`, `TierHandle` and `BlobStore` in one
Interfaces block that #10 creates — so a key on any of those, or on any of their members, resolves
when #10 lands and an implementation is still absent. Review measured all four candidate keys
firing against a Protocol-only module. These are keyed on `open_store`, which appears in no
Interfaces block and so cannot exist before an implementation does.
"""

from __future__ import annotations

import pytest
from hypothesis import given, settings

from tests.support.fuzz_strategies import blob_payloads, write_interleavings
from tests.support.impl import STORE_MODULE, require

pytestmark = pytest.mark.property

#: §6.7's *"500 in CI"*. See the note in `test_fuzz_06_graphs_and_work_ids.py` — `conftest`'s `ci`
#: profile registers 200, the two documents disagree, and the case-specific row wins.
FUZZ_EXAMPLES = 500

#: The declared reads `CT-STORE-01` permits. `TierHandle` offers `query`, `enqueue_write` and
#: `transaction` **and nothing else**, and `FR-STORE-08` restricts reads to keyed lookup and
#: declared statements — so the atomicity case reads back through `query()`. An earlier draft
#: called `handle.has_result()` and `handle.status()`, which would have required adding two members
#: to a protocol the design deliberately closes.
LEDGER_ROW = "SELECT status FROM work_unit WHERE work_id = :work_id"
RESULT_ROW = "SELECT count(*) AS n FROM result WHERE work_id = :work_id"

#: The two writes each transaction makes, as declared statements.
#:
#: **This is a repair, made by #11 and reported against TS-56 (#149).** The case called
#: `tx.write_result(work_id, payload=...)` and `tx.set_status(work_id, "done")` -- domain methods
#: on `Tx` that cannot be implemented, because design 3.3 says `M-STORE` "does not own any schema
#: meaning: table semantics belong to the module that owns the tier", and the ledger is
#: `M-ORCH`'s. `Tx.execute(statement, **params)` is the interface a transaction body actually has,
#: and it is what every other merged case uses. `result` likewise did not exist: #10's cohort
#: migration creates `work_unit` but no result table, so `RESULT_ROW` read a table nothing made.
#: The property, the abort and the both-or-neither invariant are untouched.
RESULT_DDL = (
    "CREATE TABLE IF NOT EXISTS result ("
    "  work_id TEXT NOT NULL PRIMARY KEY REFERENCES work_unit(work_id),"
    "  payload BLOB NOT NULL"
    ")"
)
SEED_UNIT = (
    "INSERT OR IGNORE INTO work_unit (work_id, stage, status) "
    "VALUES (:work_id, 'judge', 'pending')"
)
WRITE_RESULT = "INSERT OR REPLACE INTO result (work_id, payload) VALUES (:work_id, :payload)"
SET_STATUS = "UPDATE work_unit SET status = :status WHERE work_id = :work_id"


# --- FR-STORE-06: the content-addressed blob store ----------------------------------------------


@settings(max_examples=FUZZ_EXAMPLES, deadline=None)
@given(blob_payloads())
def test_fuzz_07_a_blob_round_trips_and_its_path_stays_inside_the_data_directory(
    tmp_data_dir, payload
):
    """*"`get(put(b)) == b`; `path()` always resolves inside the data directory"*.

    Two invariants over one generated byte string, and the second is the security one: `SEC-09`
    attacks `path()` with a crafted `content_hash` and `FR-STORE-09` requires resolution to stay
    inside the data directory. Here the hash is one the store computed itself, so this is the
    *positive* half — the path of a legitimately stored blob must never escape either, which a
    store that hashed to something containing a separator would violate with no attacker at all.
    Compared after `resolve()`, so a `..` segment is normalized rather than passing as text.

    **`tmp_data_dir`, not `tmp_path`.** `conftest`'s fixture says why it exists: it is per-test and
    outside any world-writable temp path, *"which is what `FR-STORE-09` requires the real store to
    insist on: it raises `InsecureLocationError` for a data directory inside one."* An earlier
    draft handed `tmp_path` to `open_store`, which a compliant `M-STORE` would refuse — the test
    would have errored on correct behaviour. It also pre-creates `blobs/`.

    **On a function-scoped fixture inside `@given`.** It is the *first* parameter deliberately:
    `@given` binds its strategies to the rightmost parameters, so a fixture listed last absorbs the
    draw and pytest then hunts for a fixture named after the strategy argument — a collection
    *error*, which `tests/support/impl.py` is explicit about, since an error asserts nothing and
    looks identical to a broken import.

    `conf_builders`'s docstring records the other half: the fixture is created once and reused
    across every example rather than rebuilt per draw. Both invariants here are
    accumulation-safe — a store holding a hundred earlier blobs answers `get(put(b))` identically.
    It is **not** safe for `FR-STORE-06`'s other clause, deduplication on write, whose whole point
    is what happens when the content is already there; that case needs a fresh store per example
    and belongs with `TC-STORE-09` (#14), not here. Said out loud because the next reader will want
    to add it.
    """
    open_store = require(STORE_MODULE, "open_store", issue="#12")

    blobs = open_store(tmp_data_dir).blobs()
    content_hash = blobs.put(payload)

    assert blobs.get(content_hash) == payload, (
        f"a {len(payload)}-byte blob did not survive the round trip (FR-STORE-06)"
    )

    resolved = blobs.path(content_hash).resolve()
    assert resolved.is_relative_to(tmp_data_dir.resolve()), (
        f"path() resolved to {resolved}, outside the data directory {tmp_data_dir} "
        "(FR-STORE-06, FR-STORE-09)"
    )


# --- FR-STORE-04: result-plus-status atomicity ---------------------------------------------------


class _InjectedCrash(RuntimeError):
    """Raised inside a transaction body to abort it. Never escapes the test."""


@settings(max_examples=FUZZ_EXAMPLES, deadline=None)
@given(write_interleavings())
def test_fuzz_07_a_result_and_its_status_are_both_present_or_both_absent(
    tmp_data_dir, interleaving
):
    """*"the result-plus-status atomicity invariant holds for every interleaving"*.

    `FR-STORE-04`: *"shall commit a work unit's result and its ledger status transition in a single
    transaction."* `CT-STORE-03` says what a consumer may rely on — both present or both absent
    **after any crash**.

    **The crash is the case.** Each generated entry carries an outcome, and an `abort` raises
    between the two writes — the only moment at which a non-transactional store is distinguishable
    from a transactional one. Without it both writes always land and the invariant is trivially
    true: review demonstrated 500/500 passing against a `transaction()` that was a bare `yield`.

    The ordering matters alongside it. **Status before result** is what leaves a ledger claiming a
    unit is done with nothing stored against it — `M-ORCH` skips that unit on resume and the grade
    goes missing. `test_fuzz_generators.py` asserts both orderings, a meaningful number of aborts,
    and interleavings that revisit the same unit, are all present in the corpus.

    Read back through `query()` with declared statements, because `CT-STORE-01` closes
    `TierHandle` to `query` / `enqueue_write` / `transaction` and `FR-STORE-08` permits keyed
    lookup and declared statements only. Written against `transaction()` rather than two
    `enqueue_write` calls for the same reason the clause exists: `CT-STORE-02` makes
    `enqueue_write` asynchronous and `CT-STORE-04` gives no ordering guarantee across separate
    calls, so a caller needing both rows together must use the transaction.
    """
    open_store = require(STORE_MODULE, "open_store", issue="#11")

    handle = open_store(tmp_data_dir).cohort("c-fuzz-07")
    touched = set()

    # The ledger rows exist before the property runs, and outside the transactions under test.
    # `work_unit.status` is `NOT NULL` with a CHECK, so a transaction that only ever UPDATEs is
    # the shape the invariant is about: the row a resuming M-ORCH reads either says 'done' with a
    # result beside it, or does not.
    with handle.transaction() as tx:
        tx.execute(RESULT_DDL)
        for unit_id, _first_write, _outcome in interleaving:
            tx.execute(SEED_UNIT, work_id=f"w-{unit_id}")

    for unit_id, first_write, outcome in interleaving:
        work_id = f"w-{unit_id}"
        touched.add(work_id)
        try:
            with handle.transaction() as tx:
                if first_write == "result":
                    tx.execute(WRITE_RESULT, work_id=work_id, payload=b"result")
                    if outcome == "abort":
                        raise _InjectedCrash(work_id)
                    tx.execute(SET_STATUS, work_id=work_id, status="done")
                else:
                    tx.execute(SET_STATUS, work_id=work_id, status="done")
                    if outcome == "abort":
                        raise _InjectedCrash(work_id)
                    tx.execute(WRITE_RESULT, work_id=work_id, payload=b"result")
        except _InjectedCrash:
            pass  # the abort is the input, not a failure

    for work_id in sorted(touched):
        status_rows = handle.query(LEDGER_ROW, work_id=work_id)
        result_rows = handle.query(RESULT_ROW, work_id=work_id)

        has_status = any(row["status"] == "done" for row in status_rows)
        has_result = any(row["n"] > 0 for row in result_rows)

        assert has_result == has_status, (
            f"{work_id}: result={has_result} status={has_status} after {interleaving}. "
            "FR-STORE-04 commits both in one transaction, so a ledger row claiming done with no "
            "stored result is a unit M-ORCH will skip on resume and a grade that goes missing "
            "(CT-STORE-03)."
        )
