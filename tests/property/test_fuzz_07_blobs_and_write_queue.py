"""`FUZZ-07` — the blob store and the write queue. Test plan §6.7, TS-56 (issue #149).

| Target | Invariant |
|---|---|
| `FR-STORE-06` | `get(put(b)) == b`; `path()` always resolves inside the data directory |
| `FR-STORE-04` | The result-plus-status atomicity invariant holds for every interleaving |

**Split into two tests, keyed on two blockers.** The blob store is #12 and the write queue is #11;
both depend on #10 and neither depends on the other, so they become runnable at different moments
and keying the case as one would hold whichever landed first outside the gate.

**A caveat on both keys, reported as a finding rather than hidden.** `blocker_is_resolved`'s
`symbol` kind checks that a name *exists*, and design §3.3 declares `Store`, `TierHandle` and
`BlobStore` in one Interfaces block that #10 creates. So a key on `aeh.store:BlobStore` resolves
when #10 lands, before either implementation works. These are keyed on the most specific member
each story must supply, which narrows the window without closing it — the registry's three kinds
cannot express "an implementation exists" for a Protocol-first module. Firing early is the safer
error (the alternative is a P0 case parked outside the gate forever), but it is an error, and it
is the third time this class of problem has come up.

**The generators are tested separately and run green today** (`test_fuzz_generators.py`) — the
blob corpus is asserted to contain the empty blob, a null byte and a large payload, and the
interleaving corpus to contain a status written before its result. Without that, these invariants
hold over whatever the strategy happened to emit.
"""

